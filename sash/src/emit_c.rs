/// Per-redirect bookkeeping: the C variable holding the dup'd
/// original fd + the integer fd we wrote to. emit_restore uses
/// these to dup2 the saved copy back into place and close it.
struct SavedFdC {
    saved_var: String,
    original_fd: i64,
}

/// Mirrors emit_redirects (codegen/redirects.rs:19). For each
/// redirect: save the live fd via sash_dup, then dispatch on op.
/// Returns the saved-fd list for later emit_restore.
fn emit_redirects(
    e: &mut Emit,
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
) -> Vec<SavedFdC> {
    emit_redirects_guarded(e, redirects, types).0
}

/// Like `emit_redirects`, but also returns the first open(2)-failure guard
/// (OR-folded across multiple open redirects) so the caller can apply the
/// DD#55 setup-failure semantics (skip body, fail status, context abort).
/// Mirrors native emit_redirects_guarded (codegen/redirects.rs).
fn emit_redirects_guarded(
    e: &mut Emit,
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
) -> (Vec<SavedFdC>, Option<RedirectFailC>) {
    let mut saved = Vec::with_capacity(redirects.len());
    let mut fail: Option<RedirectFailC> = None;
    for r in redirects {
        let fd = r.fd.unwrap_or(default_fd_for_op(&r.op)) as i64;
        let t = e.fresh();
        writeln!(e.out, "    i64 {t}_saved = sash_dup({fd});", t = t, fd = fd).unwrap();
        saved.push(SavedFdC {
            saved_var: format!("{}_saved", t),
            original_fd: fd,
        });
        if let Some((f, pp, pl)) = emit_one_redirect(e, r, fd, types) {
            fail = Some(match fail {
                None => (f, pp, pl),
                Some((prev_f, prev_pp, prev_pl)) => {
                    let ot = e.fresh();
                    writeln!(e.out, "    i64 {ot} = {prev_f} | {f};", ot = ot).unwrap();
                    // Keep the first failing-candidate path for the message.
                    (ot, prev_pp, prev_pl)
                }
            });
        }
    }
    (saved, fail)
}

/// Bash default fd: stdout for write-ish ops, stdin for read-ish ops.
/// Mirrors default_fd_for_op (codegen/redirects.rs:39).
fn default_fd_for_op(op: &crate::ir::RedirectOp) -> u32 {
    use crate::ir::RedirectOp;
    match op {
        RedirectOp::Write | RedirectOp::Append | RedirectOp::DupOutput => 1,
        // `<>` is a `<` form: bash defaults it to stdin, not stdout.
        RedirectOp::Read | RedirectOp::DupInput | RedirectOp::ReadWrite => 0,
    }
}

/// open(2) flags by RedirectOp. Mirrors open_flags_for_op
/// (codegen/redirects.rs:114). Returns None for ops that don't
/// follow the open-and-dup2 pattern (DupOutput, etc.).
fn open_flags_for_op(op: &crate::ir::RedirectOp) -> Option<i64> {
    use crate::ir::RedirectOp;
    match op {
        RedirectOp::Write => Some(1),
        RedirectOp::Append => Some(2),
        RedirectOp::Read => Some(0),
        // 3 = O_RDWR|O_CREAT (no truncate) — bash's `<>`.
        RedirectOp::ReadWrite => Some(3),
        _ => None,
    }
}

/// Dispatch on RedirectOp shape. Mirrors emit_one_redirect
/// (codegen/redirects.rs:69).
fn emit_one_redirect(
    e: &mut Emit,
    r: &crate::ir::Redirect,
    fd: i64,
    types: &VarTypes,
) -> Option<RedirectFailC> {
    use crate::ir::RedirectOp;
    if let Some(flags) = open_flags_for_op(&r.op) {
        return emit_open_redirect(e, fd, &r.target, flags, types);
    }
    match r.op {
        // `>&N` and `<&N` are the same dup2(N, fd); they differ only in the fd
        // they default to, which `default_fd_for_op` already decides.
        RedirectOp::DupOutput | RedirectOp::DupInput => emit_dup_fd(e, fd, &r.target),
        // Write/Append/Read/ReadWrite were taken by open_flags_for_op above, so
        // every variant is now accounted for and this is a compiler bug. It used
        // to emit a comment, which silently dropped the redirect and left the
        // command running on the wrong fd.
        other => panic!("ICE: unhandled redirect op reached emit_redirect: {other:?}"),
    }
    None
}

/// `> file` / `>> file` / `< file`. Mirrors emit_open_redirect
/// (codegen/redirects.rs:128). Literal path → sash_redirect (which
/// internally does the open+dup2+close); dynamic path → sash_redirect_s
/// with computed (ptr, len).
/// A redirect `open(2)` failure surfaced to the command handler: the C
/// expression that is nonzero on failure, plus the target path (for the
/// `<argv0>: <path>: <reason>` diagnostic). Mirrors native RedirectFailure.
type RedirectFailC = (String, String, String);

fn emit_open_redirect(
    e: &mut Emit,
    fd: i64,
    target: &crate::ir::Expr,
    flags: i64,
    types: &VarTypes,
) -> Option<RedirectFailC> {
    let t = e.fresh();
    if let crate::ir::ExprKind::Literal(s) = &target.kind {
        // Static path — emit a NUL-terminated string literal and
        // call sash_redirect.
        let path = format!("\"{}\"", c_escape(s));
        writeln!(
            e.out,
            "    i64 {t}_rf = (sash_redirect({fd}, {path}, {flags}) < 0);",
            t = t,
            fd = fd,
            path = path,
            flags = flags
        )
        .unwrap();
        return Some((format!("{}_rf", t), path, format!("{}", s.len())));
    }
    // Dynamic path — lower via ir_expr_as_str, call sash_redirect_s.
    let (ptr, len) = ir_expr_as_str(e, target, types);
    writeln!(
        e.out,
        "    i64 {t}_rf = (sash_redirect_s({fd}, {p}, {l}, {flags}) < 0);",
        t = t,
        p = ptr,
        l = len,
        flags = flags
    )
    .unwrap();
    Some((format!("{}_rf", t), ptr, len))
}

/// `>&N` — dup2(target_fd, fd). Mirrors emit_dup_output
/// (codegen/redirects.rs:163). Non-literal targets default to fd 2
/// (matches codegen behaviour).
fn emit_dup_fd(e: &mut Emit, fd: i64, target: &crate::ir::Expr) {
    let target_fd: i64 = match &target.kind {
        crate::ir::ExprKind::Literal(s) => s.parse().unwrap_or(2),
        _ => 2,
    };
    writeln!(e.out, "    sash_dup2({tf}, {fd});", tf = target_fd, fd = fd).unwrap();
}

/// Mirrors emit_restore (codegen/redirects.rs:214). Walk saved
/// fds in reverse order: dup2 the saved copy back into the
/// original fd slot, then close the saved copy.
fn emit_restore(e: &mut Emit, saved: &[SavedFdC]) {
    for s in saved.iter().rev() {
        writeln!(
            e.out,
            "    sash_dup2({sv}, {orig}); sash_close({sv});",
            sv = s.saved_var,
            orig = s.original_fd
        )
        .unwrap();
    }
}

/// `f > out.txt`: open a redirect *scope* around an inlined function body.
/// Mirrors native `emit_redirect_push` (codegen/inst_handlers.rs).
///
/// The saved fds are copied out of the emitter's own throwaway locals into
/// this site's `__rd_saved_N_i`, which are declared at the top of main —
/// the pop runs under a different label and cannot see a local declared
/// inside the block that pushed.
///
/// `__test_result` says whether the scope opened; the block's Branch reads
/// it, so a failed `open(2)` skips the body instead of running it on the
/// wrong fds. Outside condition position (`checked`) the failure restores,
/// reports and aborts first, so that edge is never taken there.
fn emit_redirect_push(
    e: &mut Emit,
    site: u32,
    redirects: &[crate::ir::Redirect],
    checked: bool,
    types: &VarTypes,
) {
    let (saved, failure) = emit_redirects_guarded(e, redirects, types);
    for (i, s) in saved.iter().enumerate() {
        writeln!(
            e.out,
            "    __rd_saved_{site}_{i} = {sv};",
            site = site,
            i = i,
            sv = s.saved_var
        )
        .unwrap();
    }
    let Some((failed, path_ptr, path_len)) = failure else {
        writeln!(e.out, "    __test_result = 1;").unwrap();
        return;
    };
    writeln!(e.out, "    if ({failed}) {{", failed = failed).unwrap();
    writeln!(e.out, "        __exit_status = 1; __test_result = 0;").unwrap();
    // Inside END the scope is unchecked (DD#56) but the failure is still
    // reported — silence is for a *caught* failure (55.25), not a cleanup
    // one. Mirrors the native `checked || ctx.in_end_block`.
    if checked || e.end_region.contains(&e.cur_block) {
        // The pop sits on the skip path, which an abort never reaches, so
        // the fds have to go back here — an END block (DD#56) still runs.
        emit_restore(e, &saved);
        writeln!(
            e.out,
            "        sash_emsg({p}, {l}, 0, 0);",
            p = path_ptr,
            l = path_len
        )
        .unwrap();
        emit_open_failure_goto(e);
    }
    writeln!(e.out, "    }} else {{").unwrap();
    writeln!(e.out, "        __test_result = 1;").unwrap();
    writeln!(e.out, "    }}").unwrap();
}

/// Close the scope `RedirectPush { site }` opened. Mirrors native
/// `emit_redirect_pop`.
fn emit_redirect_pop(e: &mut Emit, site: u32, fds: &[i64]) {
    let saved: Vec<SavedFdC> = fds
        .iter()
        .enumerate()
        .map(|(i, fd)| SavedFdC {
            saved_var: format!("__rd_saved_{}_{}", site, i),
            original_fd: *fd,
        })
        .collect();
    emit_restore(e, &saved);
}

