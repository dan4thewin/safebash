/// No-argument "process info" intrinsics ($(epochseconds), $(signum),
/// $(getpid), $(getppid), $(random), $(getcwd), $(argc)). Split out of
/// `try_native_intrinsic_c` to keep that dispatcher under the complexity
/// gate. Returns Some when `name` is one of them.
fn try_process_intrinsic_c(e: &mut Emit, name: &str) -> Option<CStr> {
    match name {
        "epochseconds" => {
            let t = e.fresh();
            writeln!(e.out, "    sash_pair {t} = sash_epochseconds();", t = t).unwrap();
            Some((format!("{}.ptr", t), format!("{}.len", t)))
        }
        // DD#56: `$(signum)` → the last-received signal number global.
        "signum" => Some(emit_itoa_temp(e, "sash_signum")),
        "getpid" => {
            let t = e.fresh();
            writeln!(e.out, "    i64 {t}_pid = sash_getpid();", t = t).unwrap();
            Some(emit_itoa_temp(e, &format!("{}_pid", t)))
        }
        "getppid" => {
            let t = e.fresh();
            writeln!(e.out, "    i64 {t}_pid = sash_getppid();", t = t).unwrap();
            Some(emit_itoa_temp(e, &format!("{}_pid", t)))
        }
        "random" => {
            let t = e.fresh();
            writeln!(e.out, "    i64 {t}_r = sash_random();", t = t).unwrap();
            Some(emit_itoa_temp(e, &format!("{}_r", t)))
        }
        "getcwd" => {
            let t = e.fresh();
            writeln!(
                e.out,
                "    i64 {t}_l; const char* {t}_p = sash_getcwd(&{t}_l);",
                t = t
            )
            .unwrap();
            Some((format!("{}_p", t), format!("{}_l", t)))
        }
        // DD#60: $(argc) is C argc (program argv length).
        "argc" => Some(emit_itoa_temp(e, "sash_argc")),
        _ => None,
    }
}

/// Mirrors `handle_cmdsub` from codegen/value_handlers.rs:691.
/// Tries native intrinsics first (getenv, epochseconds, etc.), then the
/// external exec/capture path.
fn emit_cmdsub(e: &mut Emit, argv: &[SsaValue], suppressed: bool, types: &VarTypes) -> CStr {
    if let Some(SsaValue::Literal(name)) = argv.first() {
        if let Some(result) = try_native_intrinsic_c(e, name, argv, types) {
            return result;
        }
        return emit_cmdsub_exec_c(e, name, &argv[1..], suppressed, types);
    }
    // A non-literal head (`$( $c hi )`) is rejected by SB5011 in validate.rs,
    // the same rule statement position has always had, so reaching here means
    // the validator let one through. This used to emit a comment and capture
    // the empty string.
    panic!("ICE: command substitution with a non-literal head reached codegen")
}

/// External `$(cmd args…)` capture: build argv, fork/exec and capture stdout
/// via `sash_capture_status`, set `$?`, and abort on nonzero — mirrors native
/// `emit_cmdsub_exec` (value_handlers.rs). `suppressed` (`$(- cmd)`, DD#55)
/// discards the status and skips the abort; the captured (ptr, len) is returned
/// (trailing newline already stripped by the runtime).
fn emit_cmdsub_exec_c(
    e: &mut Emit,
    name: &str,
    args: &[SsaValue],
    suppressed: bool,
    types: &VarTypes,
) -> CStr {
    let argv = emit_argv(e, name, args, types, "    ");
    let t = e.fresh();
    writeln!(
        e.out,
        "    i64 {t}_l; i64 {t}_st; const char* {t}_p = sash_capture_status((const char* const*){argv}, sash_envp, &{t}_l, &{t}_st);",
        t = t,
        argv = argv
    )
    .unwrap();
    writeln!(
        e.out,
        "    __exit_status = {t}_st; __test_result = ({t}_st == 0) ? 1 : 0;",
        t = t
    )
    .unwrap();
    if !suppressed {
        // DD#55: same diagnostic native emits in emit_cmdsub_abort_check
        // (value_handlers.rs:875). A `-`-suppressed capture never reaches here,
        // so it stays silent.
        let esc = c_escape(name);
        writeln!(
            e.out,
            "    if ({t}_st != 0) {{ sash_emsg_status(\"{esc}\", {nl}, {t}_st); sash_exit({t}_st); }}",
            t = t,
            nl = name.len()
        )
        .unwrap();
    }
    (format!("{}_p", t), format!("{}_l", t))
}

/// Mirrors `try_native_intrinsic` (codegen/value_handlers.rs:736).
/// Returns Some when the command is a sash-native intrinsic.
/// Phase 3 implements: getenv, epochseconds, getpid, getppid, getcwd.
/// Deferred to Phase 4: argc, argv, signum (need argv access plumbing
/// or are tied to status handling).
fn try_native_intrinsic_c(
    e: &mut Emit,
    name: &str,
    argv: &[SsaValue],
    types: &VarTypes,
) -> Option<CStr> {
    if let Some(r) = try_process_intrinsic_c(e, name) {
        return Some(r);
    }
    match name {
        "arg" if argv.len() >= 3 => {
            // DD#60 addendum: $(arg N DEFAULT) — argv[N], or the default if OOB.
            let (ip, il) = lower_value_as_str(e, &argv[1], types);
            let (dp, dl) = lower_value_as_str(e, &argv[2], types);
            let t = e.fresh();
            writeln!(
                e.out,
                "    i64 {t}_i = sash_atoi({ip}, {il}); i64 {t}_l; \
                 const char* {t}_p = sash_argv_get_or({t}_i, {dp}, {dl}, &{t}_l);",
                t = t,
                ip = ip,
                il = il,
                dp = dp,
                dl = dl
            )
            .unwrap();
            Some((format!("{}_p", t), format!("{}_l", t)))
        }
        "arg" if argv.len() >= 2 => {
            // DD#60: $(arg N) — scalar program argument, 0-based.
            let (ip, il) = lower_value_as_str(e, &argv[1], types);
            let t = e.fresh();
            writeln!(
                e.out,
                "    i64 {t}_i = sash_atoi({ip}, {il}); i64 {t}_l; \
                 const char* {t}_p = sash_argv_get({t}_i, &{t}_l);",
                t = t,
                ip = ip,
                il = il
            )
            .unwrap();
            Some((format!("{}_p", t), format!("{}_l", t)))
        }
        "getenv" if argv.len() >= 2 => {
            let (np, nl) = lower_value_as_str(e, &argv[1], types);
            let t = e.fresh();
            writeln!(
                e.out,
                "    i64 {t}_l; const char* {t}_p = sash_getenv({np}, {nl}, &{t}_l);",
                t = t,
                np = np,
                nl = nl
            )
            .unwrap();
            // DD#101: the lookup status. NULL means absent; a present name
            // yields a pointer into environ even when its value is empty, so
            // the pointer — never the length — is what separates unset from
            // set-to-empty. Mirrors value_handlers::emit_getenv_lookup_status.
            writeln!(e.out, "    __exit_status = ({t}_p == 0) ? 1 : 0;", t = t).unwrap();
            Some((format!("{}_p", t), format!("{}_l", t)))
        }
        _ => None,
    }
}

