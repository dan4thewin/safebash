/// Mirrors handle_pipeline (codegen/inst_handlers.rs:24). Forks
/// one child per stage, wires pipes between consecutive stages
/// via dup2, parent waits for all children, exit status comes
/// from the last stage.
///
/// When `capture_read_fd` (DD#20 lastpipe), an extra pipe carries the
/// final stage's stdout to the parent: its read end is stashed in
/// `__pipe_read_fd` for a following ReadLine/ReadLineMulti/Mapfile
/// (fd=-1) to consume in-process. Mirrors save_capture_fd /
/// parent_close_pipes (codegen/inst_handlers.rs).
fn emit_pipeline(
    e: &mut Emit,
    stages: &[(String, Vec<SsaValue>, Vec<crate::ir::Redirect>)],
    checked: bool,
    capture_read_fd: bool,
    suppressed: &[bool],
    negated: &[bool],
    types: &VarTypes,
) {
    if emit_degenerate_pipeline(e, stages, checked, capture_read_fd, types) {
        return;
    }
    let n = stages.len();

    let p = e.fresh();
    // With capture, an extra pipe (index n-1) carries last-stage → parent.
    let num_pipes = if capture_read_fd { n } else { n - 1 };
    writeln!(e.out, "    /* pipeline: {} stages */", n).unwrap();

    emit_pipeline_create_pipes(e, &p, num_pipes);
    // pid slots — one per stage.
    writeln!(e.out, "    i64 {p}_pids[{n}];", p = p, n = n).unwrap();

    for (i, (name, args, redirects)) in stages.iter().enumerate() {
        emit_pipeline_stage(
            e,
            &p,
            i,
            n,
            num_pipes,
            capture_read_fd,
            name,
            args,
            redirects,
            types,
        );
    }

    emit_pipeline_parent_close(e, &p, num_pipes, capture_read_fd);
    emit_pipeline_finish(e, &p, checked, suppressed, negated, stages);
}

/// A 0- or 1-stage "pipeline" needs none of the fork/pipe machinery. Returns
/// true when it handled the case. Split out of `emit_pipeline` to keep that
/// function under the complexity gate.
fn emit_degenerate_pipeline(
    e: &mut Emit,
    stages: &[(String, Vec<SsaValue>, Vec<crate::ir::Redirect>)],
    checked: bool,
    capture_read_fd: bool,
    types: &VarTypes,
) -> bool {
    let n = stages.len();
    if n == 0 {
        return true;
    }
    if n == 1 && !capture_read_fd {
        // Degenerate 1-stage pipeline: emit as a plain command carrying the
        // pipeline's own `checked` so a bare failing stage still aborts.
        let (name, args, redirects) = &stages[0];
        let kind = BuiltinCmd::from_name(name);
        emit_command(e, name, &kind, args, redirects, checked, types);
        return true;
    }
    false
}

/// Reap the children, publish the aggregate status, and apply the DD#55 abort.
/// Split out of `emit_pipeline` to keep that function under the complexity gate.
fn emit_pipeline_finish(
    e: &mut Emit,
    p: &str,
    checked: bool,
    suppressed: &[bool],
    negated: &[bool],
    stages: &[(String, Vec<SsaValue>, Vec<crate::ir::Redirect>)],
) {
    emit_pipeline_wait(e, p, suppressed, negated, stages);
    writeln!(e.out, "    __exit_status = {p}_status;", p = p).unwrap();
    writeln!(e.out, "    __test_result = (__exit_status == 0) ? 1 : 0;").unwrap();
    // DD#55: a nonzero aggregate aborts in a `checked` (statement) position;
    // `checked` is false in condition / END positions (no abort there). The
    // diagnostic names the stage that actually failed, which `{p}_fail` carried
    // out of the first-nonzero fold in emit_pipeline_wait.
    if checked {
        let abort = abort_target(e);
        writeln!(
            e.out,
            "    if (__exit_status != 0) {{ sash_emsg_status({p}_fail, {p}_fail_len, \
             __exit_status); goto {abort}; }}",
            p = p
        )
        .unwrap();
    }
}

/// Create `num_pipes` anonymous pipes for a pipeline.
fn emit_pipeline_create_pipes(e: &mut Emit, p: &str, num_pipes: usize) {
    for i in 0..num_pipes {
        writeln!(
            e.out,
            "    i64 {p}_pipe{i}[2]; sash_pipe({p}_pipe{i});",
            p = p,
            i = i
        )
        .unwrap();
    }
}

/// Parent closes all pipe fds after forking, except (when capturing) the
/// final pipe's read end, which is stashed in `__pipe_read_fd`.
fn emit_pipeline_parent_close(e: &mut Emit, p: &str, num_pipes: usize, capture_read_fd: bool) {
    for i in 0..num_pipes {
        if capture_read_fd && i == num_pipes - 1 {
            writeln!(e.out, "    sash_close({p}_pipe{i}[1]);", p = p, i = i).unwrap();
            writeln!(e.out, "    __pipe_read_fd = {p}_pipe{i}[0];", p = p, i = i).unwrap();
        } else {
            writeln!(
                e.out,
                "    sash_close({p}_pipe{i}[0]); sash_close({p}_pipe{i}[1]);",
                p = p,
                i = i
            )
            .unwrap();
        }
    }
}

/// Parent waits for (reaps) all `n` children, computing the DD#55
/// aggregate = first-nonzero status over the NON-suppressed stages.
/// A `-`-suppressed stage still ran; only its status is excluded. DD#70: a
/// `!`-negated stage inverts its status (0↔nonzero) before the fold.
fn emit_pipeline_wait(
    e: &mut Emit,
    p: &str,
    suppressed: &[bool],
    negated: &[bool],
    stages: &[(String, Vec<SsaValue>, Vec<crate::ir::Redirect>)],
) {
    writeln!(e.out, "    i64 {p}_status = 0;", p = p).unwrap();
    // DD#55: the diagnostic names the FAILING stage, not the last one, so the
    // name is captured by the same first-nonzero fold that picks the status
    // (native materializes all stage names and lets wait_for_children pick —
    // inst_handlers.rs:68). A null name is skipped by sash_emsg_status.
    writeln!(
        e.out,
        "    const char* {p}_fail = 0; i64 {p}_fail_len = 0;",
        p = p
    )
    .unwrap();
    for (i, stage) in stages.iter().enumerate() {
        let is_suppressed = suppressed.get(i).copied().unwrap_or(false);
        let is_negated = negated.get(i).copied().unwrap_or(false);
        if is_suppressed {
            writeln!(e.out, "    sash_wait({p}_pids[{i}]);", p = p, i = i).unwrap();
            continue;
        }
        let st = if is_negated {
            // invert: a negated stage is true (0) exactly when it failed.
            format!("(({p}_st == 0) ? 1 : 0)", p = p)
        } else {
            format!("{p}_st", p = p)
        };
        let esc = c_escape(&stage.0);
        let nl = stage.0.len();
        writeln!(
            e.out,
            "    {{ i64 {p}_st = sash_wait({p}_pids[{i}]); i64 {p}_s2 = {st}; \
             if ({p}_status == 0 && {p}_s2 != 0) {{ {p}_status = {p}_s2; \
             {p}_fail = \"{esc}\"; {p}_fail_len = {nl}; }} }}",
            p = p,
            i = i,
            st = st
        )
        .unwrap();
    }
}

/// One pipeline stage. Mirrors lower_pipeline_stage
/// (codegen/inst_handlers.rs:118). Fork; in child wire pipes via
/// dup2 + close all pipe fds + exec; in parent record pid.
///
/// `num_pipes` is n-1 normally, or n with `capture_read_fd` (the extra
/// pipe carries the last stage's stdout to the parent). The last stage
/// wires stdout to that capture pipe when capturing.
#[allow(clippy::too_many_arguments)]
fn emit_pipeline_stage(
    e: &mut Emit,
    p: &str,
    i: usize,
    n: usize,
    num_pipes: usize,
    capture_read_fd: bool,
    name: &str,
    args: &[SsaValue],
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
) {
    writeln!(e.out, "    {p}_pids[{i}] = sash_fork();", p = p, i = i).unwrap();
    writeln!(
        e.out,
        "    if ({p}_pids[{i}] == 0) {{  /* child {i} */",
        p = p,
        i = i
    )
    .unwrap();

    emit_stage_child_pipes(e, p, i, n, num_pipes, capture_read_fd);

    // Stage-level redirects (these go inside the child).
    if !redirects.is_empty() {
        let _saved = emit_redirects(e, redirects, types);
        // Child exits after exec; no need to restore.
    }

    // Run the command. If it's an inline builtin, emit the body
    // then exit. Otherwise sash_exec replaces the process image.
    let kind = BuiltinCmd::from_name(name);
    match kind {
        BuiltinCmd::Echo => {
            emit_echo(e, args, false, types);
            writeln!(e.out, "        sash_exit(0);").unwrap();
        }
        BuiltinCmd::Noop => {
            writeln!(e.out, "        sash_exit(0);").unwrap();
        }
        // DD#14: a compound command (fn body, `{ }` group, loop) used as a
        // pipeline stage. The transform lowers the body into its own SSA block
        // and names the stage `__compound_<id>`; native jumps to that block in
        // the child (inst_handlers.rs:170). The C emitter already lays every
        // SSA block down as a `_blk_<id>:` label inside the same function, so
        // the child branch is a plain `goto`. Without this the stage name fell
        // through to `emit_pipeline_exec` and became
        // `sash_exec("__compound_2", …)`, which the runtime rejects with
        // `sash: bug: bare command passed to sash_exec`.
        _ => match name.strip_prefix("__compound_") {
            Some(id) => writeln!(e.out, "        goto _blk_{};", id).unwrap(),
            None => emit_pipeline_exec(e, name, args, types),
        },
    }

    writeln!(e.out, "    }}").unwrap();
}

/// In the forked child: wire stdin from the previous pipe, stdout to the
/// next (or capture) pipe, then close every pipe fd. `num_pipes` is n-1
/// normally, or n with `capture_read_fd`.
fn emit_stage_child_pipes(
    e: &mut Emit,
    p: &str,
    i: usize,
    n: usize,
    num_pipes: usize,
    capture_read_fd: bool,
) {
    if i > 0 {
        writeln!(
            e.out,
            "        sash_dup2({p}_pipe{prev}[0], 0);",
            p = p,
            prev = i - 1
        )
        .unwrap();
    }
    if i < n - 1 || capture_read_fd {
        let pipe_idx = if i < num_pipes { i } else { num_pipes - 1 };
        writeln!(
            e.out,
            "        sash_dup2({p}_pipe{idx}[1], 1);",
            p = p,
            idx = pipe_idx
        )
        .unwrap();
    }
    for j in 0..num_pipes {
        writeln!(
            e.out,
            "        sash_close({p}_pipe{j}[0]); sash_close({p}_pipe{j}[1]);",
            p = p,
            j = j
        )
        .unwrap();
    }
}

/// Per-stage external exec. Same shape as emit_exec but uses
