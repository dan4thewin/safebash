/// Lower an `SsaTest` to a C i64 expression returning 0 or 1.
/// Mirrors `lower_test_expr` from codegen/tests.rs.
///
/// DD#62: operands are pre-lowered `SsaValue`s; the binary RHS may be a
/// literal regex/glob `Pattern`. Numeric ops (`-eq` etc.) are rejected by
/// SB5019 before codegen, so no integer-comparison path is emitted here.
fn lower_test_expr(e: &mut Emit, test: &SsaTest, types: &VarTypes) -> String {
    match test {
        SsaTest::Binary { left, op, right } => lower_test_binary(e, left, op, right, types),
        SsaTest::Unary { op, operand } => lower_test_unary(e, op, operand, types),
        SsaTest::Not(inner) => {
            // codegen/tests.rs: result = isub(iconst(1), inner_val).
            // C: (1 - inner). Since inner is 0/1, this yields 1/0.
            let v = lower_test_expr(e, inner, types);
            format!("(1 - ({}))", v)
        }
        SsaTest::And(a, b) => {
            // codegen: band(va, vb). Bitwise AND of 0/1 values.
            let va = lower_test_expr(e, a, types);
            let vb = lower_test_expr(e, b, types);
            format!("(({}) & ({}))", va, vb)
        }
        SsaTest::Or(a, b) => {
            let va = lower_test_expr(e, a, types);
            let vb = lower_test_expr(e, b, types);
            format!("(({}) | ({}))", va, vb)
        }
    }
}

/// Lower a binary test. Mirrors native `codegen/tests.rs::lower_test_binary`
/// arm for arm — string equality (=, ==, !=) and ordering (<, >) via
/// `sash_strcmp`, regex (`=~`) via `sash_regex_match`, and the file
/// comparisons (-nt, -ot, -ef) via `sash_file_newer`/`sash_file_same_dev`.
/// Numeric ops never reach here (user ones rejected by SB5019; synthesized
/// loop bounds use the `(( ))` arith path), so the fall-through is an ICE —
/// it used to emit a `/* TODO */` comment and return constant 0, which made
/// `[[ a < b ]]` silently false in c while native and bash said true.
fn lower_test_binary(
    e: &mut Emit,
    left: &SsaValue,
    op: &str,
    right: &SsaTestRhs,
    types: &VarTypes,
) -> String {
    let (lp, ll) = lower_value_as_str(e, left, types);
    let (rp, rl) = test_rhs_as_str(e, right, types);
    // codegen returns 1 ⇔ match; sash_strcmp returns 0 on match (so invert).
    match op {
        "=" | "==" => format!(
            "((sash_strcmp({}, {}, {}, {})) == 0 ? 1 : 0)",
            lp, ll, rp, rl
        ),
        "!=" => format!(
            "((sash_strcmp({}, {}, {}, {})) != 0 ? 1 : 0)",
            lp, ll, rp, rl
        ),
        // DD#63: `[[ s =~ pat ]]` — regex match via the vendored regexp9
        // engine in libsash_rt (same as native; `\w`/`\d`/`\s` supported).
        // Returns 1 ⇔ match. Subject is the LHS, pattern the RHS.
        "=~" => format!("(sash_regex_match({}, {}, {}, {}))", lp, ll, rp, rl),
        // Byte ordering, not locale collation: the runtime is locale-free, so
        // this is `LC_ALL=C` bash. Same `sash_strcmp` native uses.
        "<" => format!(
            "((sash_strcmp({}, {}, {}, {})) < 0 ? 1 : 0)",
            lp, ll, rp, rl
        ),
        ">" => format!(
            "((sash_strcmp({}, {}, {}, {})) > 0 ? 1 : 0)",
            lp, ll, rp, rl
        ),
        "-nt" => format!("(sash_file_newer({}, {}, {}, {}))", lp, ll, rp, rl),
        // `a -ot b` is `b -nt a` — operands swapped, as in native.
        "-ot" => format!("(sash_file_newer({}, {}, {}, {}))", rp, rl, lp, ll),
        "-ef" => format!("(sash_file_same_dev({}, {}, {}, {}))", lp, ll, rp, rl),
        other => panic!("ICE: unimplemented test operator: {}", other),
    }
}

/// Lower a binary test's RHS to a `(ptr, len)` C expression pair.
/// A `Pattern` RHS (regex/glob) is a literal string.
fn test_rhs_as_str(e: &mut Emit, right: &SsaTestRhs, types: &VarTypes) -> CStr {
    match right {
        SsaTestRhs::Value(v) => lower_value_as_str(e, v, types),
        SsaTestRhs::Pattern(p) => (format!("\"{}\"", c_escape(p)), format!("{}", p.len())),
    }
}

/// Lower a unary test: -n / -z (and implicit-? bare word), the DD#93
/// content-shape tests, `-t fd`, and the stat(2) file tests.
///
/// The file-test opcodes come from codegen's `file_test_op_code` rather than
/// a second table here, so the two backends cannot answer the same operator
/// differently.
fn lower_test_unary(e: &mut Emit, op: &str, operand: &SsaValue, types: &VarTypes) -> String {
    let (ptr, len) = lower_value_as_str(e, operand, types);
    match op {
        "-n" | "?" => format!("(({}) > 0 ? 1 : 0)", len),
        "-z" => format!("(({}) == 0 ? 1 : 0)", len),
        // DD#93 Part C: content-shape tests — one runtime validator each,
        // all with the same (ptr, len) -> 0/1 shape.
        "i?" => format!("sash_is_int({}, {})", ptr, len),
        "p?" => format!("sash_is_print({}, {})", ptr, len),
        "g?" => format!("sash_is_graph({}, {})", ptr, len),
        "-t" => format!("sash_isatty(sash_atoi({}, {}))", ptr, len),
        // INVARIANT: mirrors codegen/tests.rs::lower_unary. The parser's
        // is_unary_test_op gates which operators reach here; each one is
        // either handled above or is a file test, except -v/-o/-R which
        // validate rejects (SB5028). A None means parser/backend drift, not
        // user input — panic rather than emit a program that silently
        // answers "false" to every file test.
        other => match crate::codegen::file_test_op_code(other) {
            Some(code) => format!("sash_file_test({}, {}, {})", ptr, len, code),
            None => panic!("ICE: unimplemented unary test operator: {}", other),
        },
    }
}

/// IR Expr → (ptr, len) C expression pair.
/// Bridge from IR Expr (what TestExpr operands carry) into the SSA
/// lowering shape. Reads the highest-version slot for `$name` lookups.
fn ir_expr_as_str(e: &mut Emit, expr: &crate::ir::Expr, types: &VarTypes) -> CStr {
    use crate::ir::ExprKind;
    match &expr.kind {
        ExprKind::Literal(s) | ExprKind::SingleQuoted(s) => {
            (format!("\"{}\"", c_escape(s)), format!("{}", s.len()))
        }
        ExprKind::SimpleExpansion(name) => latest_var_as_str(name, types),
        ExprKind::DoubleQuoted(parts) => {
            if parts.is_empty() {
                return ("\"\"".to_string(), "0".to_string());
            }
            let (mut acc_ptr, mut acc_len) = ir_expr_as_str(e, &parts[0], types);
            for p in &parts[1..] {
                let (pp, pl) = ir_expr_as_str(e, p, types);
                let t = e.fresh();
                writeln!(
                    e.out,
                    "    i64 {t}_l; const char* {t}_p = (const char*)sash_concat({ap}, {al}, {pp}, {pl}, &{t}_l);",
                    t = t, ap = acc_ptr, al = acc_len, pp = pp, pl = pl
                )
                .unwrap();
                acc_ptr = format!("{}_p", t);
                acc_len = format!("{}_l", t);
            }
            (acc_ptr, acc_len)
        }
        // Only the four literal/expansion forms above can appear where this
        // helper is used; anything else is a lowering bug. ICE rather than
        // emit an empty string for a value we did not compute.
        _ => panic!(
            "ICE: {:?} reached ir_expr_as_str, which handles only literal and \
             simple-expansion forms",
            std::mem::discriminant(&expr.kind)
        ),
    }
}

/// Look up the highest-version slot for `name` and return its
/// (ptr, len) C expression pair. For Int vars: route through
/// sash_itoa via emit_itoa_temp (which requires `e` to emit setup).
/// For unknown vars: empty string. NB: this signature doesn't
/// thread `e` for the Int path — caller must use a String-typed
/// var. Phase 2 acknowledges this limitation; Phase 3 will widen.
fn latest_var_as_str(name: &str, types: &VarTypes) -> CStr {
    let Some(((n, v), vtype)) = highest_version(name, types) else {
        return ("\"\"".to_string(), "0".to_string());
    };
    let base = c_var_name(&n, v);
    match vtype {
        VarType::String => (format!("{}_ptr", base), format!("{}_len", base)),
        // Int var in string context inside a test op: we'd need
        // sash_itoa. Currently the test ops requiring this (e.g.
        // [[ "$intvar" = "5" ]]) are rare enough to defer.
        VarType::Int => ("\"\"".to_string(), "0".to_string()),
    }
}

/// Find the highest-version (name, version) entry for `name` in
/// the type map. Returns Some((entry, type)) if found.
fn highest_version(name: &str, types: &VarTypes) -> Option<((String, u32), VarType)> {
    types
        .iter()
        .filter(|((n, _), _)| n == name)
        .max_by_key(|((_, v), _)| *v)
        .map(|((n, v), t)| ((n.clone(), *v), *t))
}

