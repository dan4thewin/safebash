//! Emit C from SSA. The C oracle: each SSA block becomes a
//! labelled statement, each terminator becomes a `goto`. gcc reads
//! the result and produces a binary that runs the same program
//! through a second compilation path; diffing its output against
//! Cranelift's gives us a differential oracle that catches
//! transform AND codegen bugs.
//!
//! Phase 1 (this file): minimum viable — string variable
//! declarations, `echo` command via printf, exit, all four
//! terminators. Unsupported SsaValue / SsaInst / BuiltinCmd
//! variants emit `/* TODO: ... */` comments so the C still
//! compiles and the unsupported area is visible.
//!
//! See `notes/tasks/add-c-oracle.md` for the full 6-phase scope.

use std::collections::HashSet;
use std::fmt::Write;

use crate::ssa::*;

/// Emit a complete C program from an `SsaProgram`. The output is
/// self-contained: includes its own prologue and an `int main`.
pub fn emit_c(ssa: &SsaProgram) -> String {
    let mut out = String::new();
    emit_prologue(&mut out);
    emit_main(&mut out, ssa);
    out
}

fn emit_prologue(out: &mut String) {
    writeln!(out, "/* generated by sash --emit-c */").unwrap();
    writeln!(out, "#include <stdio.h>").unwrap();
    writeln!(out, "#include <stdlib.h>").unwrap();
    writeln!(out, "#include <string.h>").unwrap();
    writeln!(out).unwrap();
}

fn emit_main(out: &mut String, ssa: &SsaProgram) {
    writeln!(out, "int main(int argc, char** argv) {{").unwrap();
    writeln!(out, "    (void)argc; (void)argv;").unwrap();
    writeln!(out, "    long __exit_status = 0;").unwrap();
    writeln!(out, "    long __test_result = 0;").unwrap();
    writeln!(out, "    (void)__test_result;").unwrap();
    declare_vars(out, ssa);

    // Emit blocks in insertion order. Function bodies (fn_* labels)
    // are skipped in Phase 1 — they become C functions in Phase 4.
    let block_ids: Vec<BlockId> = ssa.blocks.keys().copied().collect();
    for &id in &block_ids {
        let block = ssa.block(id);
        if block.label.starts_with("fn_") {
            continue;
        }
        emit_block(out, id, block);
    }

    writeln!(out).unwrap();
    writeln!(out, "__exit:").unwrap();
    writeln!(out, "    return (int)__exit_status;").unwrap();
    writeln!(out, "}}").unwrap();
}

/// Scan the SSA for every (name, version) pair that gets assigned,
/// and declare one C variable per pair. Phase 1 types everything
/// as `const char*`; phase 2 will infer int vs string from arith
/// context.
fn declare_vars(out: &mut String, ssa: &SsaProgram) {
    let mut vars: HashSet<(String, u32)> = HashSet::new();
    for block in ssa.blocks.values() {
        for inst in &block.insts {
            if let SsaInst::Assign { target, .. } = inst {
                vars.insert((target.name.clone(), target.version));
            }
        }
    }
    let mut sorted: Vec<_> = vars.into_iter().collect();
    sorted.sort();
    for (name, version) in &sorted {
        let cname = c_var_name(name, *version);
        writeln!(out, "    const char* {} = \"\"; (void){};", cname, cname).unwrap();
    }
    if !sorted.is_empty() {
        writeln!(out).unwrap();
    }
}

/// Map an SSA (name, version) to a C identifier. Sanitises non-
/// alphanumerics (e.g. `$`, `?`, `@`) to underscores so the C
/// compiler accepts them.
fn c_var_name(name: &str, version: u32) -> String {
    let sanitized: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("{}_v{}", sanitized, version)
}

fn emit_block(out: &mut String, id: BlockId, block: &BasicBlock) {
    writeln!(out).unwrap();
    writeln!(out, "_blk_{}: /* {} */", id, block.label).unwrap();
    writeln!(out, "    ;").unwrap();
    for inst in &block.insts {
        emit_inst(out, inst);
    }
    emit_terminator(out, &block.terminator);
}

fn emit_inst(out: &mut String, inst: &SsaInst) {
    match inst {
        SsaInst::Assign { target, value } => {
            let lhs = c_var_name(&target.name, target.version);
            let rhs = emit_value(value);
            writeln!(out, "    {} = {};", lhs, rhs).unwrap();
        }
        SsaInst::Command {
            name, kind, args, ..
        } => {
            emit_command(out, name, kind, args);
        }
        SsaInst::Phi(node) => {
            // Phi resolution: in C we'd ordinarily wire this by
            // assigning to the phi target at each predecessor.
            // Phase 1 emits a comment; Phase 2 will properly
            // resolve at predecessor-block boundaries.
            writeln!(out, "    /* TODO phi: {:?} */", node.target).unwrap();
        }
        _ => {
            writeln!(
                out,
                "    /* TODO inst: {:?} */",
                std::mem::discriminant(inst)
            )
            .unwrap();
        }
    }
}

fn emit_value(value: &SsaValue) -> String {
    match value {
        SsaValue::Literal(s) => format!("\"{}\"", c_escape(s)),
        SsaValue::Var(vref) => c_var_name(&vref.name, vref.version),
        _ => "\"\" /* TODO value */".to_string(),
    }
}

/// Escape a string literal for C source. Handles the common
/// special characters; high bytes go through as \\xNN.
fn c_escape(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 32 => write!(out, "\\x{:02x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out
}

fn emit_command(out: &mut String, name: &str, kind: &BuiltinCmd, args: &[SsaValue]) {
    match kind {
        BuiltinCmd::Echo => emit_echo(out, args),
        BuiltinCmd::Exit => emit_exit(out, args),
        BuiltinCmd::Noop | BuiltinCmd::True => {
            writeln!(out, "    __exit_status = 0;").unwrap();
        }
        BuiltinCmd::False => {
            writeln!(out, "    __exit_status = 1;").unwrap();
        }
        _ => {
            writeln!(out, "    /* TODO command: {} ({:?}) */", name, kind).unwrap();
        }
    }
}

/// `echo arg1 arg2 ...` becomes `printf("%s %s ... %s\n", a1, a2, ..., aN);`.
/// `echo` with no args is just `puts("")`.
fn emit_echo(out: &mut String, args: &[SsaValue]) {
    if args.is_empty() {
        writeln!(out, "    puts(\"\");").unwrap();
        return;
    }
    let exprs: Vec<String> = args.iter().map(emit_value).collect();
    let fmt = (0..exprs.len()).map(|_| "%s").collect::<Vec<_>>().join(" ");
    writeln!(out, "    printf(\"{}\\n\", {});", fmt, exprs.join(", ")).unwrap();
    writeln!(out, "    __exit_status = 0;").unwrap();
}

/// `exit [N]` becomes `__exit_status = N; goto __exit;` — falls
/// through to the C `return` at the function end.
fn emit_exit(out: &mut String, args: &[SsaValue]) {
    if let Some(arg) = args.first() {
        match arg {
            SsaValue::Literal(s) => {
                let parsed: i64 = s.parse().unwrap_or(1);
                writeln!(out, "    __exit_status = {};", parsed).unwrap();
            }
            _ => {
                writeln!(out, "    /* TODO exit non-literal */").unwrap();
                writeln!(out, "    __exit_status = 1;").unwrap();
            }
        }
    }
    writeln!(out, "    goto __exit;").unwrap();
}

fn emit_terminator(out: &mut String, term: &Terminator) {
    match term {
        Terminator::Return => {
            writeln!(out, "    goto __exit;").unwrap();
        }
        Terminator::Goto(b) => {
            writeln!(out, "    goto _blk_{};", b).unwrap();
        }
        Terminator::Branch {
            true_block,
            false_block,
            ..
        } => {
            writeln!(
                out,
                "    if (__test_result) goto _blk_{}; else goto _blk_{};",
                true_block, false_block
            )
            .unwrap();
        }
        Terminator::Loop {
            body_block,
            exit_block,
            ..
        } => {
            writeln!(
                out,
                "    if (__test_result) goto _blk_{}; else goto _blk_{};",
                body_block, exit_block
            )
            .unwrap();
        }
    }
}
