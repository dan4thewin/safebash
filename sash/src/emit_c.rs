/// Emit the `main` function: variable declarations, all blocks in
/// SSA order, terminal `__exit:` label.
fn emit_main(e: &mut Emit, ssa: &SsaProgram) {
    let types = collect_var_types(ssa);
    e.end_block = ssa.end_block;
    writeln!(e.out, "int main(int argc, char** argv) {{").unwrap();
    writeln!(e.out, "    (void)argc; (void)argv;").unwrap();
    writeln!(e.out, "    i64 __exit_status = 0;").unwrap();
    writeln!(e.out, "    i64 __test_result = 0;").unwrap();
    writeln!(e.out, "    (void)__test_result;").unwrap();
    declare_vars(&mut e.out, &types);

    // Phase 1: only main-body blocks. fn_* (function bodies) come
    // in Phase 4 — they map to C function definitions.
    let block_ids: Vec<BlockId> = ssa.blocks.keys().copied().collect();
    for &id in &block_ids {
        let block = ssa.block(id);
        if block.label.starts_with("fn_") {
            continue;
        }
        emit_block(e, id, block, &types);
    }

    writeln!(e.out).unwrap();
    writeln!(e.out, "__exit:").unwrap();
    writeln!(e.out, "    sash_exit(__exit_status);").unwrap();
    writeln!(e.out, "    return 0;  /* unreachable */").unwrap();
    writeln!(e.out, "}}").unwrap();
}

/// Walk every assignment in the SSA and record the declared type
/// of each `(name, version)` pair. Type comes from `VarRef::var_type`
/// (populated by `ir_to_ssa_typed` from `infer_types`).
///
/// Phi sources AND Var references in SSA values are also recorded:
/// the SSA can reference an initial-version (`_v0`) for a variable
/// that's never explicitly assigned in the elided-function context
/// (sash's function bodies constant-fold into the caller, so
/// positional params from the caller appear as v0 refs). We
/// declare them with default zero/empty so the C compiles.
fn collect_var_types(ssa: &SsaProgram) -> VarTypes {
    let mut types: VarTypes = HashMap::new();
    for block in ssa.blocks.values() {
        for inst in &block.insts {
            collect_inst_var_types(inst, &mut types);
        }
    }
    types
}

/// Collect every var ref reachable from a single SsaInst into
/// `types`. Walks Assign target+value, Command args, Pipeline
/// stages, Phi targets+sources.
fn collect_inst_var_types(inst: &SsaInst, types: &mut VarTypes) {
    match inst {
        SsaInst::Assign { target, value } => {
            types.insert((target.name.clone(), target.version), target.var_type);
            collect_value_vars(value, types);
        }
        SsaInst::Command { args, .. } => {
            for a in args {
                collect_value_vars(a, types);
            }
        }
        SsaInst::Pipeline { stages, .. } => {
            for (_, args, _) in stages {
                for a in args {
                    collect_value_vars(a, types);
                }
            }
        }
        _ => {}
    }
}

/// Walk every Var reference inside an SsaValue, recording each in
/// `types`. Used to ensure phi sources / initial-version reads have
/// a corresponding C declaration even when no Assign target carries
/// the same (name, version) pair.
fn collect_value_vars(value: &SsaValue, types: &mut VarTypes) {
    match value {
        SsaValue::Var(vref)
        | SsaValue::ArithExpr { var: vref, .. }
        | SsaValue::ParamExpansion { var: vref, .. } => {
            types
                .entry((vref.name.clone(), vref.version))
                .or_insert(vref.var_type);
        }
        SsaValue::Concat(parts) | SsaValue::IndexedArray(parts) => {
            for p in parts {
                collect_value_vars(p, types);
            }
        }
        SsaValue::ArithBinOp { left, right, .. } => {
            collect_value_vars(left, types);
            collect_value_vars(right, types);
        }
        SsaValue::Ternary {
            cond,
            true_val,
            false_val,
        } => {
            collect_value_vars(cond, types);
            collect_value_vars(true_val, types);
            collect_value_vars(false_val, types);
        }
        SsaValue::CmdSubst { argv, .. } => {
            for v in argv {
                collect_value_vars(v, types);
            }
        }
        _ => {}
    }
}

/// Declare one C variable per distinct *name* (not per (name,
/// version) pair — see c_var_name's doc). Mirrors codegen's
/// `VarSlot` model where each bash variable maps to one
/// Cranelift `Variable`: string vars are two C variables
/// (`_ptr` plus `_len`), int vars are one. If a name appears at
/// multiple versions with different declared types we take the
/// most-Int-like (Int over String) since Int vars get reused as
/// Int across the function.
fn declare_vars(out: &mut String, types: &VarTypes) {
    // Collapse versions: name → most-int-like type seen.
    let mut by_name: HashMap<String, VarType> = HashMap::new();
    for ((name, _ver), vt) in types {
        let entry = by_name.entry(name.clone()).or_insert(*vt);
        // Int wins if any version is Int.
        if *vt == VarType::Int {
            *entry = VarType::Int;
        }
    }
    let mut sorted: Vec<_> = by_name.iter().collect();
    sorted.sort_by_key(|(name, _)| (*name).clone());
    if sorted.is_empty() {
        return;
    }
    for (name, vtype) in &sorted {
        let base = c_var_name(name, 0);
        match vtype {
            VarType::Int => {
                writeln!(out, "    i64 {} = 0; (void){};", base, base).unwrap();
            }
            VarType::String => {
                writeln!(
                    out,
                    "    const char* {0}_ptr = \"\"; i64 {0}_len = 0; (void){0}_ptr; (void){0}_len;",
                    base
                )
                .unwrap();
            }
        }
    }
    writeln!(out).unwrap();
}

/// Map an SSA `(name, version)` to a C identifier stem. **Versions
/// are dropped.** This mirrors Cranelift's SSA model: every SSA
/// version of the same bash variable is represented by ONE
/// Cranelift `Variable`, so phi nodes resolve implicitly via the
/// last-write-wins discipline at `def_var` sites. emit_c does the
/// same — one C local per variable name; assignments overwrite;
/// phi nodes are no-ops (the assignment in the predecessor already
/// wrote the right value).
///
/// Special vars like `1`, `2`, …, `9`, `#`, `?`, `$`, `@` are
/// sanitised: non-alphanumerics → `_`, and a leading digit is
/// prefixed with `p` so the C identifier is well-formed.
fn c_var_name(name: &str, _version: u32) -> String {
    let sanitized: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if sanitized
        .chars()
        .next()
        .map(|c| c.is_ascii_digit())
        .unwrap_or(true)
    {
        format!("p{}", sanitized)
    } else {
        sanitized
    }
}

fn emit_block(e: &mut Emit, id: BlockId, block: &BasicBlock, types: &VarTypes) {
    writeln!(e.out).unwrap();
    writeln!(e.out, "_blk_{}: /* {} */", id, block.label).unwrap();
    writeln!(e.out, "    ;").unwrap();
    // Caught/uncaught $? model: mirror codegen/entry.rs — at the
    // start of a catching construct's exit block, reset __exit_status
    // to 0 so caught statuses do not leak to program exit.
    if is_catching_construct_exit(&block.label) {
        writeln!(e.out, "    __exit_status = 0;").unwrap();
    }
    for inst in &block.insts {
        emit_inst(e, inst, types);
    }
    emit_terminator(&mut e.out, &block.terminator);
}

/// Same predicate as `codegen/entry.rs::is_catching_construct_exit`.
/// Keep the two in sync.
fn is_catching_construct_exit(label: &str) -> bool {
    matches!(
        label,
        "if.merge"
            | "if_bless.merge"
            | "while.exit"
            | "for.exit"
            | "for_cmd.exit"
            | "for_arr.exit"
            | "for_at.exit"
            | "dispatch.merge"
    )
}

fn emit_inst(e: &mut Emit, inst: &SsaInst, types: &VarTypes) {
    match inst {
        SsaInst::Assign { target, value } => emit_assign(e, target, value, types),
        SsaInst::Command {
            name,
            kind,
            args,
            redirects,
            checked,
        } => emit_command(e, name, kind, args, redirects, *checked, types),
        // Phase 4: SsaInst::Pipeline → fork chain with pipes.
        // Mirrors handle_pipeline (codegen/inst_handlers.rs:24).
        SsaInst::Pipeline {
            stages, checked, ..
        } => emit_pipeline(e, stages, *checked, types),
        // Phase 5: SsaInst::SubscriptAssign → sash_table_set.
        // Mirrors handle_subscript_assign (codegen/inst_handlers.rs:1070).
        SsaInst::SubscriptAssign {
            array,
            index,
            value,
            is_integer_key,
        } => emit_subscript_assign(e, array, index, value, *is_integer_key, types),
        // Phase 5: SsaInst::ReadLine → sash_read_line/sash_read_delim.
        // Single-target read (read VAR). For Phase 5 we ignore
        // redirects and clean_pipe (always read from fd given,
        // typically 0). __read_eof tracks EOF.
        SsaInst::ReadLine {
            target, fd, delim, ..
        } => emit_readline(e, target, *fd, *delim, types),
        // SsaInst::Test stores its result into __test_result. Codegen
        // (dispatch.rs:108-118): result = lower_test_expr(...);
        // builder.def_var(test_result_var, result). Branch terminator
        // then reads it.
        SsaInst::Test(test_expr) => {
            let val = lower_test_expr(e, test_expr, types);
            writeln!(e.out, "    __test_result = {};", val).unwrap();
        }
        // DD#63: `match S P ARR` out-array form → sash_regex_match_into.
        SsaInst::MatchInto {
            subject,
            pattern,
            array,
        } => emit_match_into_c(e, subject, pattern, array, types),
        _ => {
            writeln!(
                e.out,
                "    /* TODO inst: {:?} */",
                std::mem::discriminant(inst)
            )
            .unwrap();
        }
    }
}

/// `x = value;` — mirrors codegen's variable assignment.
/// For string targets: assign both `_ptr` and `_len`.
/// For int targets: assign the single i64.
fn emit_assign(e: &mut Emit, target: &VarRef, value: &SsaValue, types: &VarTypes) {
    let base = c_var_name(&target.name, target.version);
    match target.var_type {
        VarType::String => {
            let (ptr, len) = lower_value_as_str(e, value, types);
            writeln!(e.out, "    {0}_ptr = {1};", base, ptr).unwrap();
            writeln!(e.out, "    {0}_len = {1};", base, len).unwrap();
        }
        VarType::Int => {
            let int_expr = lower_value_as_int(e, value, types);
            writeln!(e.out, "    {} = {};", base, int_expr).unwrap();
        }
    }
}

/// Lower an `SsaValue` to a `(ptr, len)` C expression pair.
/// Mirrors codegen's `lower_value` from `sash/src/codegen/values.rs:289`.
///
/// If the value requires a runtime call (e.g. `sash_itoa` for an
/// int variable), this function *emits a temp declaration into `e.out`*
/// and returns expressions referencing the temp.
/// Concatenate `parts` in value position: left-fold via `sash_concat`,
/// mirroring native `lower_concat_value`. Each fold step emits a fresh
/// temp `(ptr, len)`; the final temp is returned.
fn emit_concat_value(e: &mut Emit, parts: &[SsaValue], types: &VarTypes) -> CStr {
    assert!(!parts.is_empty(), "empty Concat");
    let (mut acc_ptr, mut acc_len) = lower_value_as_str(e, &parts[0], types);
    for part in &parts[1..] {
        let (p_ptr, p_len) = lower_value_as_str(e, part, types);
        let t = e.fresh();
        writeln!(
            e.out,
            "    i64 {t}_l; const char* {t}_p = (const char*)sash_concat({a_ptr}, {a_len}, {b_ptr}, {b_len}, &{t}_l);",
            t = t,
            a_ptr = acc_ptr,
            a_len = acc_len,
            b_ptr = p_ptr,
            b_len = p_len
        )
        .unwrap();
        acc_ptr = format!("{}_p", t);
        acc_len = format!("{}_l", t);
    }
    (acc_ptr, acc_len)
}

fn lower_value_as_str(e: &mut Emit, value: &SsaValue, types: &VarTypes) -> CStr {
    match value {
        SsaValue::Literal(s) | SsaValue::Expr(s) => {
            (format!("\"{}\"", c_escape(s)), format!("{}", s.len()))
        }
        SsaValue::Var(vref) => emit_var_value(e, vref),
        SsaValue::ArithExpr { .. } | SsaValue::ArithBinOp { .. } => {
            let int_expr = lower_value_as_int(e, value, types);
            emit_itoa_temp(e, &int_expr)
        }
        // Phase 3: ${var...} → handle_param_expansion
        // (codegen/value_handlers.rs:18). Routes through the operator
        // dispatch.
        SsaValue::ParamExpansion {
            var,
            operator,
            operand,
        } => emit_param_expansion(e, var, operator, operand, types),
        // Phase 3: $(...) → handle_cmdsub
        // (codegen/value_handlers.rs:691). Tries native intrinsics
        // first; external exec is deferred to Phase 4.
        SsaValue::CmdSubst { argv, .. } => emit_cmdsub(e, argv, types),
        // Concat in value position (assignment RHS, subscript-assign value):
        // left-fold the parts through sash_concat, mirroring native
        // lower_concat_value (codegen/values.rs:314).
        SsaValue::Concat(parts) => emit_concat_value(e, parts, types),
        // DD#63: $(sub/gsub S P R) → real Plan 9 engine via the sash
        // runtime (the same sash_regex_replace native uses), called with
        // the sash_pair ABI like sash_substring.
        SsaValue::RegexReplace {
            subject,
            pattern,
            replacement,
            global,
        } => emit_regex_replace_c(e, subject, pattern, replacement, *global, types),
        // DD#63: $(match S P) → whole match via sash_regex_match_str.
        SsaValue::RegexMatch { subject, pattern } => emit_regex_match_c(e, subject, pattern, types),
        // DD#65: $(toupper s) / $(tolower s) — reuse the case-conversion runtime.
        SsaValue::CaseConvert { subject, upper } => {
            let (s_ptr, s_len) = lower_value_as_str(e, subject, types);
            emit_case_conversion_c(e, if *upper { "^^" } else { ",," }, &s_ptr, &s_len)
        }
        // Phase 5 table/array/argv reads, plus the unhandled fallback.
        other => lower_value_as_str_aggregate(e, other, types),
    }
}

/// Phase 5 aggregate/positional reads (array & map literals, subscript
/// reads, table-iteration helpers, argv-slice reads) plus the
/// not-yet-supported fallback. Split out of `lower_value_as_str` to keep
/// that dispatcher under the complexity gate.
fn lower_value_as_str_aggregate(e: &mut Emit, value: &SsaValue, types: &VarTypes) -> CStr {
    match value {
        // Phase 5: array / map literals → sash_table_new + per-elem set.
        SsaValue::IndexedArray(elems) => emit_indexed_array(e, elems, types),
        SsaValue::AssocArray(pairs) => emit_assoc_array(e, pairs, types),
        // DD#60: argv-slice loop var (argv[idx], 0-based) / argv snapshot.
        SsaValue::ArgvIndex(_) | SsaValue::ArgvSnapshot { .. } => emit_c_argv_value(e, value),
        // Phase 5: subscript read: ${arr[i]} or ${map[k]}.
        SsaValue::Subscript {
            array,
            index,
            is_integer_key,
        } => emit_subscript_value(e, array, index, *is_integer_key, types),
        // Phase 5: table iteration helpers (for x in "${arr[@]}").
        SsaValue::TableValue { array, index } => emit_table_value(e, array, index, types),
        SsaValue::TableKey { array, index } => emit_table_key(e, array, index, types),
        _ => {
            writeln!(
                e.out,
                "    /* TODO lower_value_as_str: {:?} */",
                std::mem::discriminant(value)
            )
            .unwrap();
            ("\"\"".to_string(), "0".to_string())
        }
    }
}

/// Lower an `SsaValue::Var` to a (ptr, len) pair. `$?`/`$$` route through
/// `sash_itoa` on the live int value (codegen/values.rs:514-525).
fn emit_var_value(e: &mut Emit, vref: &VarRef) -> CStr {
    if vref.name == "?" {
        return emit_itoa_temp(e, "__exit_status");
    }
    if vref.name == "$" {
        let t = e.fresh();
        writeln!(e.out, "    i64 {t}_pid = sash_getpid();", t = t).unwrap();
        return emit_itoa_temp(e, &format!("{}_pid", t));
    }
    match vref.var_type {
        VarType::String => {
            let base = c_var_name(&vref.name, vref.version);
            (format!("{}_ptr", base), format!("{}_len", base))
        }
        VarType::Int => emit_itoa_temp(e, &c_var_name(&vref.name, vref.version)),
    }
}

/// DD#60: `ArgvIndex` (argv[idx], 0-based — the loop guard keeps idx in
/// range) and `ArgvSnapshot` (`array a=$(argv N)` → `sash_argv_snapshot`).
fn emit_c_argv_value(e: &mut Emit, value: &SsaValue) -> CStr {
    match value {
        SsaValue::ArgvIndex(idx_ref) => {
            let iv = c_var_name(&idx_ref.name, idx_ref.version);
            let t = e.fresh();
            writeln!(
                e.out,
                "    i64 {t}_i = sash_atoi({iv}_ptr, {iv}_len); i64 {t}_l; \
                 const char* {t}_p = sash_argv_get({t}_i, &{t}_l);",
                t = t,
                iv = iv
            )
            .unwrap();
            (format!("{}_p", t), format!("{}_l", t))
        }
        SsaValue::ArgvSnapshot { start } => {
            let t = e.fresh();
            writeln!(
                e.out,
                "    void* {t}_tab = sash_argv_snapshot({start});",
                t = t,
                start = start
            )
            .unwrap();
            (format!("(const char*){}_tab", t), "0".to_string())
        }
        _ => unreachable!("emit_c_argv_value: non-argv value"),
    }
}

/// Emit `i64 __tN_l; const char* __tN_p = (const char*)sash_itoa(int_expr, &__tN_l);`
/// and return `("__tN_p", "__tN_l")`. Mirrors codegen's stack-slot
/// pattern in `emit_int_to_str` (codegen/types.rs:217). The two
/// locals must be evaluated together as the (ptr, len) pair; C
/// evaluation order forces us to materialise them before use.
fn emit_itoa_temp(e: &mut Emit, int_expr: &str) -> CStr {
    let t = e.fresh();
    writeln!(
        e.out,
        "    i64 {t}_l; const char* {t}_p = (const char*)sash_itoa({val}, &{t}_l);",
        t = t,
        val = int_expr
    )
    .unwrap();
    (format!("{}_p", t), format!("{}_l", t))
}

/// Lower an `SsaValue` to a C i64 expression for arith / comparison
/// context. Mirrors `lower_value_as_int` from codegen/values.rs:877.
/// String vars go through `sash_atoi`; int vars pass through;
/// literals parse as i64 if numeric, else `sash_atoi` over the bytes.
/// ArithExpr / ArithBinOp recurse through `arith_op_c`.
#[allow(clippy::only_used_in_recursion)]
fn lower_value_as_int(e: &mut Emit, value: &SsaValue, types: &VarTypes) -> String {
    match value {
        SsaValue::Literal(s) | SsaValue::Expr(s) => s
            .parse::<i64>()
            .map(|n| n.to_string())
            .unwrap_or_else(|_| format!("sash_atoi(\"{}\", {})", c_escape(s), s.len())),
        SsaValue::Var(vref) => {
            if vref.name == "?" {
                return "__exit_status".to_string();
            }
            if vref.name == "$" {
                return "sash_getpid()".to_string();
            }
            match vref.var_type {
                VarType::Int => c_var_name(&vref.name, vref.version),
                VarType::String => {
                    let base = c_var_name(&vref.name, vref.version);
                    format!("sash_atoi({}_ptr, {}_len)", base, base)
                }
            }
        }
        // codegen/values.rs:341+ for ArithExpr: lower_value_as_int(Var(var))
        // then emit_arith_op(op, lhs, iconst(operand)).
        SsaValue::ArithExpr { var, op, operand } => {
            let lhs = lower_value_as_int(e, &SsaValue::Var(var.clone()), types);
            emit_arith_op_c(e, *op, &lhs, &operand.to_string())
        }
        // codegen/values.rs:356+ for ArithBinOp: lower_value_as_int(left/right)
        // then emit_arith_op(op, l, r).
        SsaValue::ArithBinOp { left, op, right } => {
            let l = lower_value_as_int(e, left, types);
            let r = lower_value_as_int(e, right, types);
            emit_arith_op_c(e, *op, &l, &r)
        }
        _ => {
            // Fallback (e.g. ${arr arrlen}, subscripts): lower as a string
            // then sash_atoi. Mirrors codegen's lower_value_as_int fallback.
            let (ptr, len) = lower_value_as_str(e, value, types);
            format!("sash_atoi({}, {})", ptr, len)
        }
    }
}

/// Emit a C i64 expression for an arithmetic op on already-lowered
/// operands. Mirrors `emit_arith_op` from codegen/arithmetic.rs:14.
///
/// Comparison ops (Eq..Ge) yield 0/1 via C `(lhs OP rhs)` which is
/// already i64-typed in C semantics (bool result widened in
/// assignment context, which is what __test_result expects).
///
/// Div/Mod include a zero check via a fresh helper local that
/// matches codegen's emit_div_by_zero_error behaviour: writes
/// bash's "division by 0" message to stderr and returns 0.
///
/// Pow routes through `sash_pow` (mirrors codegen's externs.pow).
fn emit_arith_op_c(e: &mut Emit, op: ArithOp, lhs: &str, rhs: &str) -> String {
    use ArithOp::*;
    match op {
        Add | Sub | Mul => emit_checked_arith_c(e, op, lhs, rhs),
        Div | Mod => emit_div_or_mod_c(e, op, lhs, rhs),
        And => format!("({} && {})", lhs, rhs),
        Or => format!("({} || {})", lhs, rhs),
        Shl => format!("({} << {})", lhs, rhs),
        Shr => format!("({} >> {})", lhs, rhs),
        BitAnd => format!("({} & {})", lhs, rhs),
        BitOr => format!("({} | {})", lhs, rhs),
        BitXor => format!("({} ^ {})", lhs, rhs),
        Eq => format!("(({} == {}) ? 1 : 0)", lhs, rhs),
        Ne => format!("(({} != {}) ? 1 : 0)", lhs, rhs),
        Lt => format!("(({} < {}) ? 1 : 0)", lhs, rhs),
        Le => format!("(({} <= {}) ? 1 : 0)", lhs, rhs),
        Gt => format!("(({} > {}) ? 1 : 0)", lhs, rhs),
        Ge => format!("(({} >= {}) ? 1 : 0)", lhs, rhs),
        Pow => format!("sash_pow({}, {})", lhs, rhs),
    }
}

/// DD#25: `+`, `-`, `*` with a runtime overflow trap (not silent
/// wraparound), mirroring native `emit_checked_arith`. Uses the C
/// `__builtin_{add,sub,mul}_overflow` intrinsics; on overflow, calls
/// `sash_arith_overflow` (writes the diagnostic and exits).
/// bug-runtime-arith-overflow-wraps.
fn emit_checked_arith_c(e: &mut Emit, op: ArithOp, lhs: &str, rhs: &str) -> String {
    let builtin = match op {
        ArithOp::Add => "__builtin_add_overflow",
        ArithOp::Sub => "__builtin_sub_overflow",
        ArithOp::Mul => "__builtin_mul_overflow",
        _ => unreachable!("emit_checked_arith_c only handles Add/Sub/Mul"),
    };
    let t = e.fresh();
    writeln!(e.out, "    i64 {t}_l = ({});", lhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_r = ({});", rhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_v;", t = t).unwrap();
    writeln!(
        e.out,
        "    if ({b}({t}_l, {t}_r, &{t}_v)) {{ sash_arith_overflow(); }}",
        b = builtin,
        t = t
    )
    .unwrap();
    format!("{}_v", t)
}

/// Emit a Div or Mod operation with bash's div-by-zero semantics:
/// stderr message + result = 0 + don't crash. Mirrors codegen's
/// `emit_div_or_mod_with_zero_check` (codegen/arithmetic.rs:66).
/// Uses a fresh temp because both operand evaluations and the
/// dispatch must happen-before the consumer reads the result.
fn emit_div_or_mod_c(e: &mut Emit, op: ArithOp, lhs: &str, rhs: &str) -> String {
    let t = e.fresh();
    let is_div = matches!(op, ArithOp::Div);
    writeln!(e.out, "    i64 {t}_l = ({});", lhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_r = ({});", rhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_v;", t = t).unwrap();
    writeln!(e.out, "    if ({t}_r == 0) {{", t = t).unwrap();
    writeln!(
        e.out,
        "        sash_write(2, \"bash: division by 0 (error token is \\\"0\\\")\\n\", 41);"
    )
    .unwrap();
    writeln!(e.out, "        __exit_status = 1;").unwrap();
    writeln!(e.out, "        {}_v = 0;", t).unwrap();
    // DD#25: INT64_MIN / -1 overflows; in C both `/` and `%` lower to idiv,
    // which #DEs (SIGFPE) for that case. Div traps (sash_arith_overflow);
    // Mod's true result is 0 (matching native srem).
    // bug-runtime-arith-overflow-wraps.
    writeln!(
        e.out,
        "    }} else if ({t}_l == (-9223372036854775807L - 1) && {t}_r == -1) {{",
        t = t
    )
    .unwrap();
    if is_div {
        writeln!(e.out, "        sash_arith_overflow();").unwrap();
    } else {
        writeln!(e.out, "        {}_v = 0;", t).unwrap();
    }
    writeln!(e.out, "    }} else {{").unwrap();
    let c_op = if is_div { "/" } else { "%" };
    writeln!(e.out, "        {t}_v = {t}_l {} {t}_r;", c_op, t = t).unwrap();
    writeln!(e.out, "    }}").unwrap();
    format!("{}_v", t)
}

/// Escape a string literal for C source.
fn c_escape(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 32 => write!(out, "\\x{:02x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out
}

/// Dispatch on `BuiltinCmd`. Phase 1 implements echo, exit, true,
/// false, noop. Phase 4 adds external command exec via the `Other`
/// arm. Phase 6 adds LetExit (the post-arith-test status setter).
/// Other builtins emit a `TODO` comment so the C still compiles and
/// the unsupported area is visible.
fn emit_command(
    e: &mut Emit,
    name: &str,
    kind: &BuiltinCmd,
    args: &[SsaValue],
    redirects: &[crate::ir::Redirect],
    checked: bool,
    types: &VarTypes,
) {
    // Phase 4: redirects wrap the command. emit_redirects → lower_exec
    // → emit_restore (codegen/inst_handlers.rs:585+).
    let saved = if redirects.is_empty() {
        Vec::new()
    } else {
        emit_redirects(e, redirects, types)
    };

    match kind {
        BuiltinCmd::Echo => {
            emit_echo(e, args, types);
            // &&/|| chains branch on the status: a successful echo must leave
            // status 0 (else a following `&& cmd` sees a stale nonzero and is
            // skipped). Write-failure/EPIPE abort is handled separately (DD#55).
            writeln!(e.out, "    __exit_status = 0;").unwrap();
            writeln!(e.out, "    __test_result = 1;").unwrap();
        }
        BuiltinCmd::Exit => emit_exit(e, args, types),
        BuiltinCmd::Noop | BuiltinCmd::True => {
            writeln!(e.out, "    __exit_status = 0;").unwrap();
            writeln!(e.out, "    __test_result = 1;").unwrap();
        }
        BuiltinCmd::False => {
            writeln!(e.out, "    __exit_status = 1;").unwrap();
            writeln!(e.out, "    __test_result = 0;").unwrap();
        }
        BuiltinCmd::Other => emit_exec(e, name, args, checked, types),
        // Phase 6: __let_exit — convert (( … )) result to status.
        // Mirrors emit_let_exit (codegen/dispatch.rs:978). Reads
        // first arg as int; if zero → status=1, test_result=0; else
        // status=0, test_result=1.
        BuiltinCmd::LetExit => emit_let_exit(e, args, types),
        // DD#63: `match S P` boolean command → sash_regex_match (1 matched
        // / 0 not); set test_result + $? (matched ? 0 : 1).
        BuiltinCmd::Match => emit_match_c(e, args, types),
        _ => {
            writeln!(e.out, "    /* TODO command: {} ({:?}) */", name, kind).unwrap();
        }
    }

    if !saved.is_empty() {
        emit_restore(e, &saved);
    }
}

/// __let_exit: take the value of an arithmetic test (string holding
/// an int, or int directly) and convert it to test_result + status.
/// (( expr )) evaluates expr; if result is nonzero the test succeeded
/// (status 0, test_result 1); if zero, the test failed (status 1,
/// test_result 0).
fn emit_let_exit(e: &mut Emit, args: &[SsaValue], types: &VarTypes) {
    let int_val = if let Some(arg) = args.first() {
        lower_value_as_int(e, arg, types)
    } else {
        "0".to_string()
    };
    let t = e.fresh();
    writeln!(e.out, "    i64 {t}_v = {iv};", t = t, iv = int_val).unwrap();
    writeln!(e.out, "    __exit_status = ({t}_v == 0) ? 1 : 0;", t = t).unwrap();
    writeln!(e.out, "    __test_result = ({t}_v == 0) ? 0 : 1;", t = t).unwrap();
}

/// External command exec — mirrors lower_exec (codegen/commands.rs:103).
/// Build a NULL-terminated argv array on the C stack, call sash_run
/// with our envp, store the exit status into __exit_status. Also
/// sets __test_result so a Branch terminator reading it sees
/// success ⇔ exit==0.
fn emit_exec(e: &mut Emit, name: &str, args: &[SsaValue], checked: bool, types: &VarTypes) {
    let argv = emit_argv(e, name, args, types, "    ");
    writeln!(
        e.out,
        "    __exit_status = sash_run((const char* const*){argv}, sash_envp);"
    )
    .unwrap();
    writeln!(e.out, "    __test_result = (__exit_status == 0) ? 1 : 0;").unwrap();
    // DD#55 (A): an unchecked (bare / not caught by if||, not `-`-suppressed)
    // external command that exits nonzero aborts the program with that status.
    // The `checked` flag is false in condition/suppressed positions (computed
    // on the SSA), so this matches native's emit_status_abort_check.
    if checked {
        writeln!(
            e.out,
            "    if (__exit_status != 0) goto {};",
            abort_target(e)
        )
        .unwrap();
    }
}

/// DD#56: where a DD#55 (A) abort jumps — the END-cleanup block if present
/// (so cleanup / `END { exit N }` runs, with the triggering status in
/// `__exit_status`), otherwise the terminal `__exit` label.
fn abort_target(e: &Emit) -> String {
    match e.end_block {
        Some(id) => format!("_blk_{}", id),
        None => "__exit".to_string(),
    }
}

/// Build a NUL-terminated `<tN>_argv` for `[name, args…]`, expanding any
/// `@a` splat to one entry per element (DD#20/DD#22 — NO word splitting,
/// empty array → zero entries). `ind` is the leading indentation.
/// Returns the argv variable name. No splat → a fixed C array literal;
/// with a splat → a runtime-sized C99 VLA (count = 1 + #scalars +
/// Σ sash_table_len(splat)).
fn emit_argv(e: &mut Emit, name: &str, args: &[SsaValue], types: &VarTypes, ind: &str) -> String {
    let t = e.fresh();
    let argv = format!("{}_argv", t);
    if args
        .iter()
        .any(|a| matches!(a, SsaValue::ArraySplat { .. }))
    {
        emit_argv_splat(e, name, args, types, ind, &t, &argv);
    } else {
        emit_argv_fixed(e, name, args, types, ind, &argv);
    }
    argv
}

/// Fixed argv: a C array literal `{ "name", a0, a1, …, NULL }`.
fn emit_argv_fixed(
    e: &mut Emit,
    name: &str,
    args: &[SsaValue],
    types: &VarTypes,
    ind: &str,
    argv: &str,
) {
    let mut arg_ptrs: Vec<String> = Vec::with_capacity(args.len() + 1);
    arg_ptrs.push(format!("\"{}\"", c_escape(name)));
    for arg in args {
        let (ptr, _len) = lower_value_as_str(e, arg, types);
        arg_ptrs.push(ptr);
    }
    writeln!(
        e.out,
        "{ind}const char* {argv}[] = {{ {}, (const char*)0 }};",
        arg_ptrs.join(", ")
    )
    .unwrap();
}

/// Runtime VLA argv: count = 1 + #scalars + Σ sash_table_len(splat); each
/// splat contributes one entry per element.
fn emit_argv_splat(
    e: &mut Emit,
    name: &str,
    args: &[SsaValue],
    types: &VarTypes,
    ind: &str,
    t: &str,
    argv: &str,
) {
    // Cache each splat's table expression and length up front.
    let scalar_count = args
        .iter()
        .filter(|a| !matches!(a, SsaValue::ArraySplat { .. }))
        .count();
    let mut splat_lens: Vec<(String, String)> = Vec::new();
    for arg in args {
        if let SsaValue::ArraySplat { array } = arg {
            let tbl = lookup_table_var(array, types);
            let len = format!("{}_len{}", t, splat_lens.len());
            writeln!(e.out, "{ind}i64 {len} = sash_table_len((SashTable*){tbl});").unwrap();
            splat_lens.push((tbl, len));
        }
    }
    let total = std::iter::once(format!("{}", 1 + scalar_count))
        .chain(splat_lens.iter().map(|(_, l)| l.clone()))
        .collect::<Vec<_>>()
        .join(" + ");
    writeln!(e.out, "{ind}i64 {t}_n = {total};").unwrap();
    writeln!(e.out, "{ind}const char* {argv}[{t}_n + 1];").unwrap();
    writeln!(e.out, "{ind}i64 {t}_w = 0;").unwrap();
    writeln!(e.out, "{ind}{argv}[{t}_w++] = \"{}\";", c_escape(name)).unwrap();

    let mut si = 0;
    for arg in args {
        if let SsaValue::ArraySplat { .. } = arg {
            let (tbl, len) = &splat_lens[si];
            si += 1;
            let iv = format!("{}_i{}", t, si);
            writeln!(
                e.out,
                "{ind}for (i64 {iv} = 0; {iv} < {len}; {iv}++) {{ i64 {t}_el; \
                 {argv}[{t}_w++] = sash_table_value((SashTable*){tbl}, {iv}, &{t}_el); }}"
            )
            .unwrap();
        } else {
            let (ptr, _len) = lower_value_as_str(e, arg, types);
            writeln!(e.out, "{ind}{argv}[{t}_w++] = {ptr};").unwrap();
        }
    }
    writeln!(e.out, "{ind}{argv}[{t}_w] = (const char*)0;").unwrap();
}

/// Echo: mirrors `lower_echo` from codegen/commands.rs:21.
///
/// For each arg: lower to (ptr, len), call sash_write(1, ptr, len).
/// Between args: write a single space via sash_write(1, " ", 1).
/// After args: write a single newline via sash_write(1, "\\n", 1).
/// With `-n` flag (first arg): suppress trailing newline.
fn emit_echo(e: &mut Emit, args: &[SsaValue], types: &VarTypes) {
    let (print_args, suppress_newline) = match args.first() {
        Some(SsaValue::Literal(flag)) if flag == "-n" => (&args[1..], true),
        _ => (args, false),
    };

    for (i, arg) in print_args.iter().enumerate() {
        if i > 0 {
            writeln!(e.out, "    sash_write(1, \" \", 1);").unwrap();
        }
        // Concat values write each part sequentially (no spaces).
        if let SsaValue::Concat(parts) = arg {
            for part in parts {
                let (ptr, len) = lower_value_as_str(e, part, types);
                writeln!(e.out, "    sash_write(1, {}, {});", ptr, len).unwrap();
            }
        } else {
            let (ptr, len) = lower_value_as_str(e, arg, types);
            writeln!(e.out, "    sash_write(1, {}, {});", ptr, len).unwrap();
        }
    }

    if !suppress_newline {
        writeln!(e.out, "    sash_write(1, \"\\n\", 1);").unwrap();
    }
    writeln!(e.out, "    __exit_status = 0;").unwrap();
}

/// Exit: mirrors codegen's exit lowering. `exit N` becomes
/// `__exit_status = N; goto __exit;`. Bare `exit` keeps the
/// previous status. Int-typed arg passes through; string-typed
/// arg routes through `sash_atoi`.
fn emit_exit(e: &mut Emit, args: &[SsaValue], types: &VarTypes) {
    if let Some(arg) = args.first() {
        let int_expr = lower_value_as_int(e, arg, types);
        writeln!(e.out, "    __exit_status = {};", int_expr).unwrap();
    }
    writeln!(e.out, "    goto __exit;").unwrap();
}

/// Mirrors codegen's terminator emission (codegen/entry.rs).
/// Return → `goto __exit;`. Goto(b) → `goto _blk_{b};`. Branch
/// and Loop both compare `__test_result` and dispatch.
fn emit_terminator(out: &mut String, term: &Terminator) {
    match term {
        Terminator::Return => {
            writeln!(out, "    goto __exit;").unwrap();
        }
        Terminator::Goto(b) => {
            writeln!(out, "    goto _blk_{};", b).unwrap();
        }
        Terminator::Branch {
            true_block,
            false_block,
            ..
        }
        | Terminator::Loop {
            body_block: true_block,
            exit_block: false_block,
            ..
        } => {
            writeln!(
                out,
                "    if (__test_result) goto _blk_{}; else goto _blk_{};",
                true_block, false_block
            )
            .unwrap();
        }
    }
}

