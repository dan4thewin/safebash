/// The DD#55 open(2) guard around an arbitrary body — the closure-taking
/// sibling of [`emit_redirect_guarded_body`], for the reads, whose body is
/// not a `BuiltinCmd` dispatch. On an open failure the body is skipped (no
/// misroute), status is 1, and — unless caught by an if/`||` condition —
/// the `<argv0>: <path>: <reason>` diagnostic is written and the program
/// aborts. Mirrors native `emit_redirect_guarded_body`.
fn emit_guarded_body(
    e: &mut Emit,
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
    body: impl FnOnce(&mut Emit, &VarTypes),
) {
    let (saved, failure) = if redirects.is_empty() {
        (Vec::new(), None)
    } else {
        emit_redirects_guarded(e, redirects, types)
    };
    let Some((failed, path_ptr, path_len)) = failure else {
        body(e, types);
        if !saved.is_empty() {
            emit_restore(e, &saved);
        }
        return;
    };
    let in_condition = e.in_condition;
    writeln!(e.out, "    if ({failed}) {{").unwrap();
    writeln!(e.out, "        __exit_status = 1; __test_result = 0;").unwrap();
    if !in_condition {
        writeln!(e.out, "        sash_emsg({path_ptr}, {path_len}, 0, 0);").unwrap();
    }
    emit_restore(e, &saved);
    if !in_condition {
        emit_open_failure_goto(e);
    }
    writeln!(e.out, "    }} else {{").unwrap();
    body(e, types);
    emit_restore(e, &saved);
    writeln!(e.out, "    }}").unwrap();
}

/// `readline VAR` — assign one newline-terminated record from `fd` to
/// `target`. Mirrors the native `emit_readline`. Sets __exit_status = 1
/// on EOF, 0 otherwise.
fn emit_readline(
    e: &mut Emit,
    target: &VarRef,
    fd: i64,
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
) {
    // `readline VAR < file` / `readline VAR <<< word` — apply the redirect
    // (e.g. herestring → fd 0) around the read, then restore. DD#55: a
    // failed open aborts rather than reading an empty line.
    emit_guarded_body(e, redirects, types, |e, _types| {
        emit_readline_body(e, target, fd)
    });
}

fn emit_readline_body(e: &mut Emit, target: &VarRef, fd: i64) {
    let t = e.fresh();
    let fdx = c_read_fd(fd);
    writeln!(
        e.out,
        "    sash_pair {t} = sash_read_line({fd});",
        t = t,
        fd = fdx
    )
    .unwrap();
    let base = c_var_name(&target.name, target.version);
    writeln!(e.out, "    {0}_ptr = {1}.ptr;", base, t).unwrap();
    writeln!(e.out, "    {0}_len = {1}.len;", base, t).unwrap();
    // EOF iff the returned ptr is NULL — the runtime distinguishes true EOF
    // (NULL, 0) from an empty line (non-NULL, 0). This is the *loop
    // condition*: `while readline x` branches on __test_result, so assigning
    // __exit_status here left the condition reading whatever the previous
    // statement had set, and the loop never noticed EOF at all — a body that
    // survived an empty read spun forever. Mirrors native
    // (codegen/dispatch.rs:emit_readline_body).
    writeln!(
        e.out,
        "    __test_result = ({t}.ptr != (const char*)0) ? 1 : 0;",
        t = t
    )
    .unwrap();
}

/// The C fd expression for a read: fd=-1 is the lastpipe sentinel
/// (consume the captured pipe read end), else the literal fd.
fn c_read_fd(fd: i64) -> String {
    if fd == -1 {
        "__pipe_read_fd".to_string()
    } else {
        fd.to_string()
    }
}

/// DD#99 `read ARRAY` — slurp `fd` and split it on NUL into `array`.
/// Mirrors the native `emit_read_array`: sash_read_all +
/// sash_split_into_array.
fn emit_read_array(
    e: &mut Emit,
    array: &str,
    fd: i64,
    redirects: &[crate::ir::Redirect],
    types: &VarTypes,
) {
    // DD#55: `read ARR < nosuch` aborts rather than yielding an empty array.
    emit_guarded_body(e, redirects, types, |e, types| {
        emit_read_array_body(e, array, fd, types)
    });
}

fn emit_read_array_body(e: &mut Emit, array: &str, fd: i64, types: &VarTypes) {
    let table_expr = lookup_table_var(array, types);
    let fdx = c_read_fd(fd);
    let t = e.fresh();
    writeln!(
        e.out,
        "    sash_pair {t} = sash_read_all({fd});",
        t = t,
        fd = fdx
    )
    .unwrap();
    writeln!(e.out, "    __test_result = ({t}.len > 0) ? 1 : 0;", t = t).unwrap();
    // DD#99: NUL is the only separator, with terminator semantics.
    writeln!(
        e.out,
        "    if ({t}.ptr) sash_split_into_array({t}.ptr, {t}.len, 0, 1, (unsigned char*){tbl});",
        t = t,
        tbl = table_expr
    )
    .unwrap();
}

#[cfg(test)]
mod tests {
    use super::*;

    // `ice_unreachable_command` is the c backend's "this variant cannot be a
    // command by the time codegen runs" guard. Every one of its arms is
    // unreachable from any accepted program — that is the property it exists to
    // assert — so the spec suite can never enter it, and a unit test
    // simulating the regression is the only way to exercise it.
    //
    // Each case stands for a different reason the variant cannot arrive, and
    // the three panic messages say which. A regression that stopped rewriting
    // `write`, or stopped resolving an expression intrinsic in transform, would
    // land here; these tests confirm it lands loudly rather than falling
    // through to a wrong emission.
    fn ices(kind: BuiltinCmd, name: &str) -> String {
        let caught = std::panic::catch_unwind(move || ice_unreachable_command(&kind, name));
        let payload = caught.expect_err("ice_unreachable_command must panic");
        payload
            .downcast_ref::<String>()
            .cloned()
            .unwrap_or_else(|| "non-string panic payload".to_string())
    }

    #[test]
    fn rewritten_before_codegen_is_a_loud_ice() {
        // DD#99 `write` is rewritten to a newline-suppressed `echo` in
        // transform/cmd_handlers.rs::rewrite_write_as_echo.
        let msg = ices(BuiltinCmd::Write, "write");
        assert!(msg.contains("rewritten before codegen"), "got: {msg}");
    }

    #[test]
    fn expression_intrinsic_as_a_command_is_a_loud_ice() {
        // Resolved to an SsaValue during transform, so it never survives as a
        // command. `strlen` is the one that moved families in DD#102.
        let msg = ices(BuiltinCmd::Strlen, "strlen");
        assert!(msg.contains("expression intrinsic"), "got: {msg}");
    }

    #[test]
    fn own_instruction_variant_as_a_command_is_a_loud_ice() {
        // Carried by its own SsaInst (`read` → SsaInst::ReadLine), so reaching
        // emit_command_body means the transform stopped lowering it.
        let msg = ices(BuiltinCmd::Read, "read");
        assert!(msg.contains("lowered to its own instruction"), "got: {msg}");
    }
}
