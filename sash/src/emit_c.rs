//! Emit C from SSA — differential oracle against Cranelift codegen.
//!
//! **Architecture: mirror codegen, not bash.** Every emit_c function
//! has a 1:1 correspondence with a function in `sash/src/codegen/`.
//! Where codegen calls `externs.itoa(...)`, emit_c emits a C call to
//! `sash_itoa(...)`. Where codegen stores a string as a (ptr, len)
//! pair (per DD#12), emit_c declares `const char* x_ptr; i64 x_len;`.
//! Where codegen routes through `lower_value_as_int` (which calls
//! `sash_atoi` for string vars), emit_c does the same — same
//! coercion at the same SSA shape, every time.
//!
//! The C output declares the sash-rt C ABI as extern and is linked
//! against `libsash_rt.a` — the same library Cranelift output links.
//! Differential = running both binaries on the same input and
//! comparing stdout / exit. Any divergence is a compiler bug.
//!
//! Phase 1 scope: literal echo, exit, string variable assignment,
//! all four terminators. No arithmetic, conditionals, or loops yet
//! — those are the next slice.
//!
//! See `notes/tasks/add-c-oracle.md` for the full 6-phase plan.

use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::VarType;
use crate::ssa::*;

/// String-typed SSA values lower to a (ptr_expr, len_expr) pair of
/// C expressions. Mirrors codegen's `(cranelift_ir::Value,
/// cranelift_ir::Value)` return shape from `lower_value`.
type CStr = (String, String);
type VarTypes = HashMap<(String, u32), VarType>;

/// Mutable emission state — output buffer + temp-name counter.
/// The counter lets us emit fresh `__tN` locals when a value needs
/// a setup statement (e.g. `sash_itoa` for Int→Str). Mirrors
/// codegen's per-call-site stack slot allocation.
struct Emit {
    out: String,
    next_temp: usize,
}

impl Emit {
    fn new() -> Self {
        Self {
            out: String::new(),
            next_temp: 0,
        }
    }
    fn fresh(&mut self) -> String {
        let n = self.next_temp;
        self.next_temp += 1;
        format!("__t{}", n)
    }
}

/// Emit a complete C program from an `SsaProgram`. The output is
/// self-contained: prologue with extern declarations, `int main`,
/// and a `__exit:` label that calls sash_exit with the status.
pub fn emit_c(ssa: &SsaProgram) -> String {
    let mut e = Emit::new();
    emit_prologue(&mut e.out);
    emit_main(&mut e, ssa);
    e.out
}

/// Prologue: extern declarations for the sash-rt C-ABI functions
/// we depend on. Matches the signatures in `sash-rt/src/lib.rs`.
/// Phase 1 only needs `sash_write`, `sash_exit`, `sash_itoa`,
/// `sash_atoi`, `sash_strcmp` — added as later phases need them.
fn emit_prologue(out: &mut String) {
    writeln!(out, "/* generated by sash --emit-c */").unwrap();
    writeln!(
        out,
        "/* differential oracle: links libsash_rt.a, same as Cranelift output */"
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "typedef long i64;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/* sash-rt C ABI (subset for Phase 2) */").unwrap();
    writeln!(
        out,
        "extern i64 sash_write(i64 fd, const char* buf, i64 len);"
    )
    .unwrap();
    writeln!(
        out,
        "extern void sash_exit(i64 status) __attribute__((noreturn));"
    )
    .unwrap();
    writeln!(out, "extern i64 sash_atoi(const char* p, i64 n);").unwrap();
    writeln!(out, "extern char* sash_itoa(i64 val, i64* out_len);").unwrap();
    writeln!(
        out,
        "extern i64 sash_strcmp(const char* p1, i64 l1, const char* p2, i64 l2);"
    )
    .unwrap();
    writeln!(out, "extern i64 sash_pow(i64 base, i64 exp);").unwrap();
    writeln!(
        out,
        "extern i64 sash_fnmatch(const char* p, i64 pl, const char* s, i64 sl);"
    )
    .unwrap();
    writeln!(
        out,
        "extern i64 sash_file_test(const char* p, i64 l, i64 op);"
    )
    .unwrap();
    writeln!(out).unwrap();
}

/// Emit the `main` function: variable declarations, all blocks in
/// SSA order, terminal `__exit:` label.
fn emit_main(e: &mut Emit, ssa: &SsaProgram) {
    let types = collect_var_types(ssa);
    writeln!(e.out, "int main(int argc, char** argv) {{").unwrap();
    writeln!(e.out, "    (void)argc; (void)argv;").unwrap();
    writeln!(e.out, "    i64 __exit_status = 0;").unwrap();
    writeln!(e.out, "    i64 __test_result = 0;").unwrap();
    writeln!(e.out, "    (void)__test_result;").unwrap();
    declare_vars(&mut e.out, &types);

    // Phase 1: only main-body blocks. fn_* (function bodies) come
    // in Phase 4 — they map to C function definitions.
    let block_ids: Vec<BlockId> = ssa.blocks.keys().copied().collect();
    for &id in &block_ids {
        let block = ssa.block(id);
        if block.label.starts_with("fn_") {
            continue;
        }
        emit_block(e, id, block, &types);
    }

    writeln!(e.out).unwrap();
    writeln!(e.out, "__exit:").unwrap();
    writeln!(e.out, "    sash_exit(__exit_status);").unwrap();
    writeln!(e.out, "    return 0;  /* unreachable */").unwrap();
    writeln!(e.out, "}}").unwrap();
}

/// Walk every assignment in the SSA and record the declared type
/// of each `(name, version)` pair. Type comes from `VarRef::var_type`
/// (populated by `ir_to_ssa_typed` from `infer_types`).
fn collect_var_types(ssa: &SsaProgram) -> VarTypes {
    let mut types: VarTypes = HashMap::new();
    for block in ssa.blocks.values() {
        for inst in &block.insts {
            match inst {
                SsaInst::Assign { target, .. } => {
                    types.insert((target.name.clone(), target.version), target.var_type);
                }
                SsaInst::Phi(node) => {
                    types.insert(
                        (node.target.name.clone(), node.target.version),
                        node.target.var_type,
                    );
                }
                _ => {}
            }
        }
    }
    types
}

/// Declare one C variable per `(name, version)` pair. Mirrors
/// codegen's `VarSlot` model: string vars are *two* C variables
/// (`_ptr` + `_len`), int vars are one.
fn declare_vars(out: &mut String, types: &VarTypes) {
    let mut sorted: Vec<_> = types.iter().collect();
    sorted.sort_by_key(|((name, ver), _)| (name.clone(), *ver));
    if sorted.is_empty() {
        return;
    }
    for ((name, version), vtype) in &sorted {
        let base = c_var_name(name, *version);
        match vtype {
            VarType::Int => {
                writeln!(out, "    i64 {} = 0; (void){};", base, base).unwrap();
            }
            VarType::String => {
                writeln!(
                    out,
                    "    const char* {0}_ptr = \"\"; i64 {0}_len = 0; (void){0}_ptr; (void){0}_len;",
                    base
                )
                .unwrap();
            }
        }
    }
    writeln!(out).unwrap();
}

/// Map an SSA `(name, version)` to a C identifier stem. Strings
/// get `_ptr` / `_len` suffixes at the use site.
fn c_var_name(name: &str, version: u32) -> String {
    let sanitized: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("{}_v{}", sanitized, version)
}

fn emit_block(e: &mut Emit, id: BlockId, block: &BasicBlock, types: &VarTypes) {
    writeln!(e.out).unwrap();
    writeln!(e.out, "_blk_{}: /* {} */", id, block.label).unwrap();
    writeln!(e.out, "    ;").unwrap();
    for inst in &block.insts {
        emit_inst(e, inst, types);
    }
    emit_terminator(&mut e.out, &block.terminator);
}

fn emit_inst(e: &mut Emit, inst: &SsaInst, types: &VarTypes) {
    match inst {
        SsaInst::Assign { target, value } => emit_assign(e, target, value, types),
        SsaInst::Command {
            name, kind, args, ..
        } => emit_command(e, name, kind, args, types),
        // SsaInst::Test stores its result into __test_result. Codegen
        // (dispatch.rs:108-118): result = lower_test_expr(...);
        // builder.def_var(test_result_var, result). Branch terminator
        // then reads it.
        SsaInst::Test(test_expr) => {
            let val = lower_test_expr(e, test_expr, types);
            writeln!(e.out, "    __test_result = {};", val).unwrap();
        }
        _ => {
            writeln!(
                e.out,
                "    /* TODO inst: {:?} */",
                std::mem::discriminant(inst)
            )
            .unwrap();
        }
    }
}

/// `x = value;` — mirrors codegen's variable assignment.
/// For string targets: assign both `_ptr` and `_len`.
/// For int targets: assign the single i64.
fn emit_assign(e: &mut Emit, target: &VarRef, value: &SsaValue, types: &VarTypes) {
    let base = c_var_name(&target.name, target.version);
    match target.var_type {
        VarType::String => {
            let (ptr, len) = lower_value_as_str(e, value, types);
            writeln!(e.out, "    {0}_ptr = {1};", base, ptr).unwrap();
            writeln!(e.out, "    {0}_len = {1};", base, len).unwrap();
        }
        VarType::Int => {
            let int_expr = lower_value_as_int(e, value, types);
            writeln!(e.out, "    {} = {};", base, int_expr).unwrap();
        }
    }
}

/// Lower an `SsaValue` to a `(ptr, len)` C expression pair.
/// Mirrors codegen's `lower_value` from `sash/src/codegen/values.rs:289`.
///
/// If the value requires a runtime call (e.g. `sash_itoa` for an
/// int variable), this function *emits a temp declaration into `e.out`*
/// and returns expressions referencing the temp. That preserves
/// single-evaluation semantics — C evaluation order of function
/// arguments is unspecified, so we can't rely on `sash_write(1,
/// sash_itoa(x, &len), len)` reading `len` after `sash_itoa` writes
/// it.
fn lower_value_as_str(e: &mut Emit, value: &SsaValue, types: &VarTypes) -> CStr {
    match value {
        // Literal / Expr: codegen interns and returns ptr + compile-
        // time length. C: bare string literal + literal byte count.
        SsaValue::Literal(s) | SsaValue::Expr(s) => {
            (format!("\"{}\"", c_escape(s)), format!("{}", s.len()))
        }
        // Var: codegen reads the VarSlot's two registers. For Int
        // vars codegen routes through sash_itoa — mirror exactly.
        SsaValue::Var(vref) => match vref.var_type {
            VarType::String => {
                let base = c_var_name(&vref.name, vref.version);
                (format!("{}_ptr", base), format!("{}_len", base))
            }
            VarType::Int => emit_itoa_temp(e, &c_var_name(&vref.name, vref.version)),
        },
        // ArithExpr / ArithBinOp in string context: codegen calls
        // emit_arith_op then emit_int_to_str (codegen/values.rs:341+).
        // We compute the int expression then route through itoa.
        SsaValue::ArithExpr { .. } | SsaValue::ArithBinOp { .. } => {
            let int_expr = lower_value_as_int(e, value, types);
            emit_itoa_temp(e, &int_expr)
        }
        _ => {
            writeln!(
                e.out,
                "    /* TODO lower_value_as_str: {:?} */",
                std::mem::discriminant(value)
            )
            .unwrap();
            ("\"\"".to_string(), "0".to_string())
        }
    }
}

/// Emit `i64 __tN_l; const char* __tN_p = (const char*)sash_itoa(int_expr, &__tN_l);`
/// and return `("__tN_p", "__tN_l")`. Mirrors codegen's stack-slot
/// pattern in `emit_int_to_str` (codegen/types.rs:217). The two
/// locals must be evaluated together as the (ptr, len) pair; C
/// evaluation order forces us to materialise them before use.
fn emit_itoa_temp(e: &mut Emit, int_expr: &str) -> CStr {
    let t = e.fresh();
    writeln!(
        e.out,
        "    i64 {t}_l; const char* {t}_p = (const char*)sash_itoa({val}, &{t}_l);",
        t = t,
        val = int_expr
    )
    .unwrap();
    (format!("{}_p", t), format!("{}_l", t))
}

/// Lower an `SsaValue` to a C i64 expression for arith / comparison
/// context. Mirrors `lower_value_as_int` from codegen/values.rs:877.
/// String vars go through `sash_atoi`; int vars pass through;
/// literals parse as i64 if numeric, else `sash_atoi` over the bytes.
/// ArithExpr / ArithBinOp recurse through `arith_op_c`.
#[allow(clippy::only_used_in_recursion)]
fn lower_value_as_int(e: &mut Emit, value: &SsaValue, types: &VarTypes) -> String {
    match value {
        SsaValue::Literal(s) | SsaValue::Expr(s) => s
            .parse::<i64>()
            .map(|n| n.to_string())
            .unwrap_or_else(|_| format!("sash_atoi(\"{}\", {})", c_escape(s), s.len())),
        SsaValue::Var(vref) => match vref.var_type {
            VarType::Int => c_var_name(&vref.name, vref.version),
            VarType::String => {
                let base = c_var_name(&vref.name, vref.version);
                format!("sash_atoi({}_ptr, {}_len)", base, base)
            }
        },
        // codegen/values.rs:341+ for ArithExpr: lower_value_as_int(Var(var))
        // then emit_arith_op(op, lhs, iconst(operand)).
        SsaValue::ArithExpr { var, op, operand } => {
            let lhs = lower_value_as_int(e, &SsaValue::Var(var.clone()), types);
            emit_arith_op_c(e, *op, &lhs, &operand.to_string())
        }
        // codegen/values.rs:356+ for ArithBinOp: lower_value_as_int(left/right)
        // then emit_arith_op(op, l, r).
        SsaValue::ArithBinOp { left, op, right } => {
            let l = lower_value_as_int(e, left, types);
            let r = lower_value_as_int(e, right, types);
            emit_arith_op_c(e, *op, &l, &r)
        }
        _ => "0 /* TODO value_as_int */".to_string(),
    }
}

/// Emit a C i64 expression for an arithmetic op on already-lowered
/// operands. Mirrors `emit_arith_op` from codegen/arithmetic.rs:14.
///
/// Comparison ops (Eq..Ge) yield 0/1 via C `(lhs OP rhs)` which is
/// already i64-typed in C semantics (bool result widened in
/// assignment context, which is what __test_result expects).
///
/// Div/Mod include a zero check via a fresh helper local that
/// matches codegen's emit_div_by_zero_error behaviour: writes
/// bash's "division by 0" message to stderr and returns 0.
///
/// Pow routes through `sash_pow` (mirrors codegen's externs.pow).
fn emit_arith_op_c(e: &mut Emit, op: ArithOp, lhs: &str, rhs: &str) -> String {
    use ArithOp::*;
    match op {
        Add => format!("({} + {})", lhs, rhs),
        Sub => format!("({} - {})", lhs, rhs),
        Mul => format!("({} * {})", lhs, rhs),
        Div | Mod => emit_div_or_mod_c(e, op, lhs, rhs),
        And => format!("({} && {})", lhs, rhs),
        Or => format!("({} || {})", lhs, rhs),
        Not => format!("(!{})", lhs), // unary; rhs ignored
        Shl => format!("({} << {})", lhs, rhs),
        Shr => format!("({} >> {})", lhs, rhs),
        BitAnd => format!("({} & {})", lhs, rhs),
        BitOr => format!("({} | {})", lhs, rhs),
        BitXor => format!("({} ^ {})", lhs, rhs),
        Eq => format!("(({} == {}) ? 1 : 0)", lhs, rhs),
        Ne => format!("(({} != {}) ? 1 : 0)", lhs, rhs),
        Lt => format!("(({} < {}) ? 1 : 0)", lhs, rhs),
        Le => format!("(({} <= {}) ? 1 : 0)", lhs, rhs),
        Gt => format!("(({} > {}) ? 1 : 0)", lhs, rhs),
        Ge => format!("(({} >= {}) ? 1 : 0)", lhs, rhs),
        Pow => format!("sash_pow({}, {})", lhs, rhs),
    }
}

/// Emit a Div or Mod operation with bash's div-by-zero semantics:
/// stderr message + result = 0 + don't crash. Mirrors codegen's
/// `emit_div_or_mod_with_zero_check` (codegen/arithmetic.rs:66).
/// Uses a fresh temp because both operand evaluations and the
/// dispatch must happen-before the consumer reads the result.
fn emit_div_or_mod_c(e: &mut Emit, op: ArithOp, lhs: &str, rhs: &str) -> String {
    let t = e.fresh();
    writeln!(e.out, "    i64 {t}_l = ({});", lhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_r = ({});", rhs, t = t).unwrap();
    writeln!(e.out, "    i64 {t}_v;", t = t).unwrap();
    writeln!(e.out, "    if ({t}_r == 0) {{", t = t).unwrap();
    writeln!(
        e.out,
        "        sash_write(2, \"bash: division by 0 (error token is \\\"0\\\")\\n\", 41);"
    )
    .unwrap();
    writeln!(e.out, "        __exit_status = 1;").unwrap();
    writeln!(e.out, "        {}_v = 0;", t).unwrap();
    writeln!(e.out, "    }} else {{").unwrap();
    let c_op = if matches!(op, ArithOp::Div) { "/" } else { "%" };
    writeln!(e.out, "        {t}_v = {t}_l {} {t}_r;", c_op, t = t).unwrap();
    writeln!(e.out, "    }}").unwrap();
    format!("{}_v", t)
}

/// Escape a string literal for C source.
fn c_escape(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 32 => write!(out, "\\x{:02x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out
}

/// Dispatch on `BuiltinCmd`. Phase 1 implements echo, exit, true,
/// false, noop. Other builtins emit a `TODO` comment so the C
/// still compiles and the unsupported area is visible.
fn emit_command(e: &mut Emit, name: &str, kind: &BuiltinCmd, args: &[SsaValue], types: &VarTypes) {
    match kind {
        BuiltinCmd::Echo => emit_echo(e, args, types),
        BuiltinCmd::Exit => emit_exit(e, args, types),
        BuiltinCmd::Noop | BuiltinCmd::True => {
            writeln!(e.out, "    __exit_status = 0;").unwrap();
        }
        BuiltinCmd::False => {
            writeln!(e.out, "    __exit_status = 1;").unwrap();
        }
        _ => {
            writeln!(e.out, "    /* TODO command: {} ({:?}) */", name, kind).unwrap();
        }
    }
}

/// Echo: mirrors `lower_echo` from codegen/commands.rs:21.
///
/// For each arg: lower to (ptr, len), call sash_write(1, ptr, len).
/// Between args: write a single space via sash_write(1, " ", 1).
/// After args: write a single newline via sash_write(1, "\\n", 1).
/// With `-n` flag (first arg): suppress trailing newline.
fn emit_echo(e: &mut Emit, args: &[SsaValue], types: &VarTypes) {
    let (print_args, suppress_newline) = match args.first() {
        Some(SsaValue::Literal(flag)) if flag == "-n" => (&args[1..], true),
        _ => (args, false),
    };

    for (i, arg) in print_args.iter().enumerate() {
        if i > 0 {
            writeln!(e.out, "    sash_write(1, \" \", 1);").unwrap();
        }
        // Concat values write each part sequentially (no spaces).
        if let SsaValue::Concat(parts) = arg {
            for part in parts {
                let (ptr, len) = lower_value_as_str(e, part, types);
                writeln!(e.out, "    sash_write(1, {}, {});", ptr, len).unwrap();
            }
        } else {
            let (ptr, len) = lower_value_as_str(e, arg, types);
            writeln!(e.out, "    sash_write(1, {}, {});", ptr, len).unwrap();
        }
    }

    if !suppress_newline {
        writeln!(e.out, "    sash_write(1, \"\\n\", 1);").unwrap();
    }
    writeln!(e.out, "    __exit_status = 0;").unwrap();
}

/// Exit: mirrors codegen's exit lowering. `exit N` becomes
/// `__exit_status = N; goto __exit;`. Bare `exit` keeps the
/// previous status. Int-typed arg passes through; string-typed
/// arg routes through `sash_atoi`.
fn emit_exit(e: &mut Emit, args: &[SsaValue], types: &VarTypes) {
    if let Some(arg) = args.first() {
        let int_expr = lower_value_as_int(e, arg, types);
        writeln!(e.out, "    __exit_status = {};", int_expr).unwrap();
    }
    writeln!(e.out, "    goto __exit;").unwrap();
}

/// Mirrors codegen's terminator emission (codegen/entry.rs).
/// Return → `goto __exit;`. Goto(b) → `goto _blk_{b};`. Branch
/// and Loop both compare `__test_result` and dispatch.
fn emit_terminator(out: &mut String, term: &Terminator) {
    match term {
        Terminator::Return => {
            writeln!(out, "    goto __exit;").unwrap();
        }
        Terminator::Goto(b) => {
            writeln!(out, "    goto _blk_{};", b).unwrap();
        }
        Terminator::Branch {
            true_block,
            false_block,
            ..
        }
        | Terminator::Loop {
            body_block: true_block,
            exit_block: false_block,
            ..
        } => {
            writeln!(
                out,
                "    if (__test_result) goto _blk_{}; else goto _blk_{};",
                true_block, false_block
            )
            .unwrap();
        }
    }
}

