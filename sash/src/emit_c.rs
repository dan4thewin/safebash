fn emit_pipeline_exec(e: &mut Emit, name: &str, args: &[SsaValue], types: &VarTypes) {
    let argv = emit_argv(e, name, args, types, "        ");
    writeln!(
        e.out,
        "        sash_exec((const char* const*){argv}, sash_envp);"
    )
    .unwrap();
}

