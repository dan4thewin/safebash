//! Emit C from SSA — differential oracle against Cranelift codegen.
//!
//! **Architecture: mirror codegen, not bash.** Every emit_c function
//! has a 1:1 correspondence with a function in `sash/src/codegen/`.
//! Where codegen calls `externs.itoa(...)`, emit_c emits a C call to
//! `sash_itoa(...)`. Where codegen stores a string as a (ptr, len)
//! pair (per DD#12), emit_c declares `const char* x_ptr; i64 x_len;`.
//! Where codegen routes through `lower_value_as_int` (which calls
//! `sash_atoi` for string vars), emit_c does the same — same
//! coercion at the same SSA shape, every time.
//!
//! The C output declares the sash-rt C ABI as extern and is linked
//! against `libsash_rt.a` — the same library Cranelift output links.
//! Differential = running both binaries on the same input and
//! comparing stdout / exit. Any divergence is a compiler bug.
//!
//! Phase 1 scope: literal echo, exit, string variable assignment,
//! all four terminators. No arithmetic, conditionals, or loops yet
//! — those are the next slice.
//!
//! See `notes/tasks/add-c-oracle.md` for the full 6-phase plan.

use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::VarType;
use crate::ssa::*;

/// String-typed SSA values lower to a (ptr_expr, len_expr) pair of
/// C expressions. Mirrors codegen's `(cranelift_ir::Value,
/// cranelift_ir::Value)` return shape from `lower_value`.
type CStr = (String, String);
type VarTypes = HashMap<(String, u32), VarType>;

/// Mutable emission state — output buffer + temp-name counter.
/// The counter lets us emit fresh `__tN` locals when a value needs
/// a setup statement (e.g. `sash_itoa` for Int→Str). Mirrors
/// codegen's per-call-site stack slot allocation.
struct Emit {
    out: String,
    next_temp: usize,
    /// DD#56: the END-cleanup block id, if the program has one. A DD#55 (A)
    /// abort routes THROUGH this block (so an `END { exit N }` / cleanup
    /// still runs) rather than exiting directly. None → jump to `__exit`.
    end_block: Option<BlockId>,
}

impl Emit {
    fn new() -> Self {
        Self {
            out: String::new(),
            next_temp: 0,
            end_block: None,
        }
    }
    fn fresh(&mut self) -> String {
        let n = self.next_temp;
        self.next_temp += 1;
        format!("__t{}", n)
    }
}

/// Emit a complete C program from an `SsaProgram`. The output is
/// self-contained: prologue with extern declarations, `int main`,
/// and a `__exit:` label that calls sash_exit with the status.
pub fn emit_c(ssa: &SsaProgram) -> String {
    let mut e = Emit::new();
    emit_prologue(&mut e.out);
    emit_main(&mut e, ssa);
    e.out
}

