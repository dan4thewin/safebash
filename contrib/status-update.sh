#!/bin/bash
# Regenerate the delimited "mk-status" block in notes/status.md from
# live truth: current branch and spec.db counts.
#
# Wired into `mk test` so drift cannot accumulate.
#
# Usage: bash contrib/status-update.sh
# Expects: spec.db at repo root, notes/status.md present with a
#          <!-- BEGIN: mk-status --> ... <!-- END: mk-status --> block.

set -eu

repo_root="$(git rev-parse --show-toplevel)"
status="$repo_root/notes/status.md"
db="$repo_root/spec.db"

if [ ! -f "$status" ]; then
    echo "status-update: $status not found" >&2
    exit 1
fi

branch="$(git -C "$repo_root" branch --show-current 2>/dev/null || echo unknown)"
today="$(date +%Y-%m-%d)"

if [ -f "$db" ]; then
    passing="$(sqlite3 "$db" "SELECT COUNT(*) FROM test_status WHERE status='passing';" 2>/dev/null || echo '?')"
    failing="$(sqlite3 "$db" "SELECT COUNT(*) FROM test_status WHERE status='failing';" 2>/dev/null || echo '?')"
    total="$(sqlite3 "$db" "SELECT COUNT(*) FROM test_status;" 2>/dev/null || echo '?')"
    last_run="$(sqlite3 "$db" "SELECT commit_hash FROM runs ORDER BY rowid DESC LIMIT 1;" 2>/dev/null || echo '?')"
else
    passing='?'; failing='?'; total='?'; last_run='no spec.db'
fi

block=$(cat <<EOF
<!-- BEGIN: mk-status (regenerated by contrib/status-update.sh) -->
## Current branch: $branch

## Spec status: $passing passing / $failing failing of $total (spec.db @ $last_run)

_Regenerated $today by \`mk status\`. Edits inside this block will be
overwritten; edit outside the BEGIN/END markers._
<!-- END: mk-status -->
EOF
)

# Use awk to splice the block in place. If the markers are absent,
# insert just below the frontmatter (after the second '---' line).
tmp="$(mktemp)"
awk -v block="$block" '
BEGIN { in_block = 0; spliced = 0; fm_lines = 0 }
/^<!-- BEGIN: mk-status/ { in_block = 1; print block; spliced = 1; next }
/^<!-- END: mk-status/ { in_block = 0; next }
in_block { next }
{ print }
' "$status" > "$tmp"

if ! grep -q '<!-- BEGIN: mk-status' "$tmp"; then
    # No marker found. Insert after the closing frontmatter '---'.
    awk -v block="$block" '
    BEGIN { fm_count = 0; spliced = 0 }
    /^---$/ {
        print
        fm_count++
        if (fm_count == 2 && !spliced) {
            print ""
            print block
            spliced = 1
        }
        next
    }
    { print }
    END {
        if (!spliced) {
            print ""
            print block
        }
    }
    ' "$status" > "$tmp"
fi

mv "$tmp" "$status"

echo "mk status: $branch | $passing/$total passing"
